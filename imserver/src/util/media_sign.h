#pragma once
#include <cstdint>
#include <initializer_list>
#include <nlohmann/json.hpp>
#include <optional>
#include <string>

// 聊天图片的限时签名:与 Django 的 im/media_sign.py 逐字节一致。
//
// 签名串 = path + "\n" + exp;签名 = HMAC-SHA256(secret, 签名串) 的小写 hex。
// exp 按整点对齐(now - now % 3600 + ttl),保证同一小时内同一张图给出同一个 URL。
class MediaSigner {
 public:
  //-------------------------------------------------------------------------------------------------------------------
  // 函数简介     构造媒体签名器 推导路径前缀并兜底 TTL
  // 参数说明     secret           签名密钥 为空表示不启用签名
  //              ttl              签名有效期秒 非正数按 86400 兜底
  //              media_prefix     IM_MEDIA_PREFIX 形如 http://host/media/chat/
  // 返回参数     void             无返回值
  // 使用示例     MediaSigner signer(secret, 3600, "http://127.0.0.1:8000/media/chat/");
  // 备注信息     path_prefix_ 由 media_prefix 推导 密钥为空时所有签名方法原样返回 URL
  //-------------------------------------------------------------------------------------------------------------------
  MediaSigner(std::string secret, int ttl, std::string media_prefix);

  // 是否启用签名(密钥为空 = 不签,开发环境)
  //-------------------------------------------------------------------------------------------------------------------
  // 函数简介     判断是否启用媒体 URL 签名
  // 参数说明     无
  // 返回参数     bool             true 表示密钥非空 需要签名
  // 使用示例     bool on = signer.enabled();
  // 备注信息     密钥为空即不启用 所有签名方法原样返回 URL 供本地开发免签名
  //-------------------------------------------------------------------------------------------------------------------
  bool enabled() const { return !secret_.empty(); }
  // IM_MEDIA_PREFIX 的路径部分(如 /media/chat/),用于从绝对 URL 里取 path
  //-------------------------------------------------------------------------------------------------------------------
  // 函数简介     取媒体前缀的路径部分
  // 参数说明     无
  // 返回参数     const std::string&  形如 /media/chat/ 的路径前缀
  // 使用示例     const std::string& prefix = signer.path_prefix();
  // 备注信息     由构造参数 media_prefix 推导 签名时用它从绝对 URL 里取 path
  //-------------------------------------------------------------------------------------------------------------------
  const std::string& path_prefix() const { return path_prefix_; }

  // 去掉 query 并校验属于 media_prefix;不合法返回 nullopt
  //-------------------------------------------------------------------------------------------------------------------
  // 函数简介     去 query 并校验 URL 属于媒体前缀
  // 参数说明     url              待规范化的绝对 URL
  // 返回参数     std::optional<std::string>  去掉 query 的 URL 前缀不匹配时返回 nullopt
  // 使用示例     auto clean = signer.canonical(url);
  // 备注信息     只保留第一个 ? 之前的部分 前缀按从头整段匹配 不做大小写折叠
  //-------------------------------------------------------------------------------------------------------------------
  std::optional<std::string> canonical(const std::string& url) const;

  // 给 URL 加 ?e=&s=(先规范化);未启用时原样返回
  //-------------------------------------------------------------------------------------------------------------------
  // 函数简介     给聊天媒体 URL 追加 e 与 s 两个签名参数
  // 参数说明     url              待签名的绝对 URL 不属于媒体前缀时原样返回
  //              now              签名基准秒 传 0 表示取当前时间
  // 返回参数     std::string      带 ?e=<exp>&s=<hex> 的 URL
  // 使用示例     std::string signed_url = signer.sign_url(url);
  // 备注信息     exp 按整点对齐 exp = now - now % 3600 + ttl 同一小时内同一张图 URL 稳定
  //-------------------------------------------------------------------------------------------------------------------
  std::string sign_url(const std::string& url, int64_t now = 0) const;

  // 就地给对象里若干 URL 字段签名(图片: url/thumb_url;语音: url)
  //-------------------------------------------------------------------------------------------------------------------
  // 函数简介     就地给 JSON 对象里若干 URL 字段加签名
  // 参数说明     object           待处理的 JSON 对象
  //              keys             要签名的字段名列表
  //              now              签名基准秒 传 0 表示取当前时间
  // 返回参数     void             无返回值
  // 使用示例     signer.sign_media(frame, {"url"});
  // 备注信息     未启用签名或不是 JSON object 时直接返回 字段不存在或非字符串时跳过该字段
  //-------------------------------------------------------------------------------------------------------------------
  void sign_media(nlohmann::json& object, std::initializer_list<const char*> keys,
                  int64_t now = 0) const;

  // 图片的薄封装
  //-------------------------------------------------------------------------------------------------------------------
  // 函数简介     给图片对象的 url 与 thumb_url 加签名
  // 参数说明     image            图片 JSON 对象
  //              now              签名基准秒 传 0 表示取当前时间
  // 返回参数     void             无返回值
  // 使用示例     signer.sign_image(image);
  // 备注信息     等价于 sign_media(image, {"url", "thumb_url"}, now)
  //-------------------------------------------------------------------------------------------------------------------
  void sign_image(nlohmann::json& image, int64_t now = 0) const;

 private:
  std::string secret_;
  std::string media_prefix_;
  std::string path_prefix_;
  int ttl_;
};
