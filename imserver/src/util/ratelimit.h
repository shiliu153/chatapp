#pragma once
#include <cstddef>
#include <cstdint>
#include <mutex>
#include <unordered_map>

class TokenBucket {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造令牌桶 桶内初始装满
// 参数说明     rate_per_second  每秒补充的令牌数
//              burst            桶容量 即允许的瞬时突发上限
// 返回参数     void             无返回值
// 使用示例     TokenBucket send_bucket_{20, 40};
// 备注信息     tokens_ 初值取 burst 启动瞬间可连续放行 burst 个请求
//-------------------------------------------------------------------------------------------------------------------
  TokenBucket(double rate_per_second, double burst);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按时间戳补充令牌并判定本次是否放行
// 参数说明     now_ms           当前毫秒时间戳 单调递增时最准
// 返回参数     bool             取到令牌返回 true 桶空返回 false
// 使用示例     if (send_bucket_.allow(now_ms)) { /* 放行这一帧 */ }
// 备注信息     非线程安全 由持有它的结构负责加锁 首次调用只记时间不补令牌
//              时间回拨按 0 计 放行时扣 1 个令牌
//-------------------------------------------------------------------------------------------------------------------
  bool allow(int64_t now_ms);

 private:
  double rate_;
  double burst_;
  double tokens_;
  int64_t last_ms_ = -1;
};

/// 按 key 共享令牌桶的限流表(线程安全)。
///
/// 设计要点:
///   1. 每个 key 一个令牌桶,第一次出现时按需创建;
///   2. 表有上限:先淘汰 10 分钟没再出现的 key,仍然满就整体清空并记警告 ——
///      只丢失一个限流窗口,绝不跟着任意 key 无限涨内存;
///   3. WS 与 HTTP 的多个入口共用这一份实现,避免每处各写一遍清理逻辑。
class RateTable {
 public:
  /// Args:
  ///   rate_per_second: 每秒补充的令牌数。
  ///   burst: 桶容量(允许的瞬时突发)。
  ///   max_entries: 表内 key 上限,超过即触发淘汰。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造限流表 记录每个 key 共用的桶参数
// 参数说明     rate_per_second  每个 key 每秒补充的令牌数
//              burst            每个 key 的桶容量
//              max_entries      表内 key 上限 默认 4096 传 0 按 1 处理
// 返回参数     void             无返回值
// 使用示例     RateTable search_table_{1.0, 20.0};
// 备注信息     桶按需创建 构造本身不建任何 key 的桶 max_entries 取 max(max_entries, 1)
//-------------------------------------------------------------------------------------------------------------------
  RateTable(double rate_per_second, double burst, std::size_t max_entries = 4096);

  /// 记账一次请求。
  ///
  /// Args:
  ///   key: 限流维度(这里是账号 id)。
  ///   now_ms: 当前毫秒时间戳。
  ///
  /// Returns:
  ///   允许本次请求返回 true。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     记账一次请求 判定该 key 是否放行
// 参数说明     key              限流维度 这里是账号 id
//              now_ms           当前毫秒时间戳
// 返回参数     bool             允许本次请求返回 true
// 使用示例     if (read_table_.allow(user_id, now_ms)) { /* 放行 */ }
// 备注信息     全程持 mutex_ 新 key 且表已满时先 evict_locked 再建桶
//              新 key 的桶从满桶开始 命中后刷新该 key 的 seen_ms
//-------------------------------------------------------------------------------------------------------------------
  bool allow(uint64_t key, int64_t now_ms);

  /// 当前表内 key 数量(测试与观测用)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     返回当前表内 key 数量
// 参数说明     无
// 返回参数     std::size_t      已创建的令牌桶个数
// 使用示例     const auto n = table.size();
// 备注信息     加锁读 供测试与观测使用 不代表在线用户数
//-------------------------------------------------------------------------------------------------------------------
  std::size_t size() const;

 private:
  /// 一个 key 的令牌桶与最近出现时间(用于淘汰空闲 key)。
  struct Entry {
    TokenBucket bucket;
    int64_t seen_ms = 0;
  };

  /// 表满时淘汰空闲 key;调用方必须已持有 ``mutex_``。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     表满时淘汰空闲 key 仍满则整体清空
// 参数说明     now_ms           当前毫秒时间戳 用于算空闲时长
// 返回参数     void             无返回值
// 使用示例     evict_locked(now_ms);  // 调用方已持有 mutex_
// 备注信息     先删 seen_ms 距今超过 600000 毫秒(10 分钟)的 key
//              清完仍达上限则打 rate_table_reset 警告并 entries_.clear() 只丢一个限流窗口
//-------------------------------------------------------------------------------------------------------------------
  void evict_locked(int64_t now_ms);

  const double rate_;
  const double burst_;
  const std::size_t max_entries_;
  mutable std::mutex mutex_;
  std::unordered_map<uint64_t, Entry> entries_;
};
