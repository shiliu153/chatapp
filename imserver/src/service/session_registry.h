#pragma once
#include <cstdint>
#include <memory>
#include <mutex>
#include <string>
#include <string_view>
#include <unordered_map>

class RedisClient;
class WsSession;

/// 在线会话表(多端在线 K-2:一个 uid 下按端各一条连接)。
///
/// 语义约定:
///   * 一个账号可以同时有 `app` 与 `web` 两条连接;**同类第二条连接互顶**(reason `multi_device`);
///   * `send_to` **扇出**到本人所有端;`kick` 踢**全部**端(封禁 / 注销);`kick_client` 只踢一端;
///   * `is_online` / `online_count` 仍**按 uid 计**(离线推送的「目标不在线」判定依赖它),
///     不按连接计 —— 任一端在线即该账号在线。
class SessionRegistry {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造在线会话表 持有 Redis 客户端引用
// 参数说明     redis           用于写在线键的 Redis 客户端 生命周期由调用方保证
// 返回参数     void             无返回值
// 使用示例     SessionRegistry registry(redis);
// 备注信息     只保存引用 不负责连接 构造不访问 Redis
//-------------------------------------------------------------------------------------------------------------------
  explicit SessionRegistry(RedisClient& redis);

  /// 注册一条已鉴权的连接;同端已有连接时把它踢下线。
  ///
  /// Args:
  ///   uid: 账号 id。
  ///   ct: 端类型 `app` / `web`。
  ///   session: 新连接。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     注册一条已鉴权连接 同端旧连接互顶
// 参数说明     uid             账号 id
//              ct              端类型 app 或 web
//              session         新连接
// 返回参数     void             无返回值
// 使用示例     registry.register_session(uid, "app", session);
// 备注信息     只踢同端 另一端不受影响 先入表再踢旧连接 旧连接迟到的注销不会误删新登记
//-------------------------------------------------------------------------------------------------------------------
  void register_session(uint64_t uid, std::string_view ct, std::shared_ptr<WsSession> session);
  /// 注销连接(只清掉仍指向该连接的那一条,避免误删新连接的登记)。
  ///
  /// Args:
  ///   uid: 账号 id。
  ///   ct: 端类型。
  ///   session: 正在关闭的连接。
  ///
  /// Returns:
  ///   该连接确实在表里并被移除时返回 true。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     注销一条连接 只清仍指向它的那条登记
// 参数说明     uid             账号 id
//              ct              端类型
//              session         正在关闭的连接
// 返回参数     bool             true 表示该连接确实在表里并被移除
// 使用示例     registry.unregister(uid, "app", session.get());
// 备注信息     比对新旧指针 该 uid 已无任何端时顺带删除外层条目
//-------------------------------------------------------------------------------------------------------------------
  bool unregister(uint64_t uid, std::string_view ct, WsSession* session);
  /// 踢掉该账号**所有端**的在线会话(封禁 / 注销账号)。
  ///
  /// Args:
  ///   uid: 账号 id。
  ///   reason: 踢下线原因,原样放进 `kicked` 帧。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     踢掉该账号所有端的在线会话
// 参数说明     uid             账号 id
//              reason          踢下线原因 原样放进 kicked 帧
// 返回参数     void             无返回值
// 使用示例     registry.kick(uid, "banned");
// 备注信息     封禁与注销账号用 等价 kick_user 传 client_type=None 锁内只收集目标 锁外踢
//-------------------------------------------------------------------------------------------------------------------
  void kick(uint64_t uid, const std::string& reason);
  /// 只踢该账号**某一端**的在线会话(同类互顶 / 按端下线)。
  ///
  /// Args:
  ///   uid: 账号 id。
  ///   ct: 端类型 `app` / `web`。
  ///   reason: 踢下线原因。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     只踢该账号某一端的在线会话
// 参数说明     uid             账号 id
//              ct              端类型 app 或 web
//              reason          踢下线原因
// 返回参数     void             无返回值
// 使用示例     registry.kick_client(uid, "web", "multi_device");
// 备注信息     同类互顶与按端下线用 只影响指定端 另一端保持在线 锁内收集 锁外踢
//-------------------------------------------------------------------------------------------------------------------
  void kick_client(uint64_t uid, std::string_view ct, const std::string& reason);
  /// 向该账号**所有端**投递一帧。
  ///
  /// Args:
  ///   uid: 账号 id。
  ///   frame: 已序列化的帧。
  ///
  /// Returns:
  ///   至少投给了一条活跃连接时返回 true(离线推送用它判「目标是否在线」)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     向该账号所有端扇出一帧
// 参数说明     uid             账号 id
//              frame           已序列化的帧
// 返回参数     bool             true 表示至少投给一条活跃连接
// 使用示例     bool online = registry.send_to(uid, frame);
// 备注信息     离线推送用它判目标是否在线 锁内只收集目标 锁外 send_raw
//-------------------------------------------------------------------------------------------------------------------
  bool send_to(uint64_t uid, const std::string& frame);
  /// 发给本人**除 `except` 之外**的所有端(跨端同步 `self_read` / `conversation_deleted` 用)。
  ///
  /// 与 `send_to` 的区别只有「跳过发起这条动作的连接」:本人另一台设备要收到,
  /// 发起端自己不需要(它的状态已经由本地操作更新,再收一遍是重复)。
  ///
  /// Args:
  ///   uid: 账号 id。
  ///   except: 不发的那条连接(通常是当前正在处理的会话)。
  ///   frame: 已序列化的帧。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     发给本人除 except 之外的所有端
// 参数说明     uid             账号 id
//              except          不发的那条连接 通常是正在处理的会话
//              frame           已序列化的帧
// 返回参数     void             无返回值
// 使用示例     registry.send_to_other_clients(uid, session, frame);
// 备注信息     跨端同步 self_read 与 conversation_deleted 用 发起端本地已更新 再收一遍是重复
//-------------------------------------------------------------------------------------------------------------------
  void send_to_other_clients(uint64_t uid, const WsSession* except, const std::string& frame);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断账号是否在线
// 参数说明     uid             账号 id
// 返回参数     bool             true 表示至少一端连接还活着
// 使用示例     bool online = registry.is_online(uid);
// 备注信息     按 uid 计 不按连接计 任一端在线即在线 离线推送的判定依赖这一口径
//-------------------------------------------------------------------------------------------------------------------
  bool is_online(uint64_t uid);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     统计在线账号数
// 参数说明     无
// 返回参数     std::size_t      在线 uid 个数
// 使用示例     std::size_t n = registry.online_count();
// 备注信息     按 uid 计 两端同时在线仍只算 1 个 持锁遍历 只用于监控
//-------------------------------------------------------------------------------------------------------------------
  std::size_t online_count();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     刷新账号在线键的 Redis TTL
// 参数说明     uid             账号 id
// 返回参数     void             无返回值
// 使用示例     registry.touch_online(uid);
// 备注信息     写 im:online:<uid> 键 TTL 90 秒 需随认证请求持续刷新 过期即视为离线 同步访问 Redis
//-------------------------------------------------------------------------------------------------------------------
  void touch_online(uint64_t uid);

 private:
  /// 端类型 → 连接。用 map 而不是 vector:按端踢是 O(1),端数固定为 2。
  using ClientSessions = std::unordered_map<std::string, std::weak_ptr<WsSession>>;

  RedisClient& redis_;
  std::mutex mutex_;
  std::unordered_map<uint64_t, ClientSessions> sessions_;
};
