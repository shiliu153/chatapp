#pragma once
#include <cstdint>
#include <optional>
#include <string>
#include <variant>
#include <vector>

#include <nlohmann/json.hpp>

#include "store/blacklist_repo.h"
#include "store/conversation_repo.h"
#include "store/message_repo.h"
#include "store/mysql_pool.h"
#include "store/user_repo.h"
#include "util/media_sign.h"

struct SendRequest {
  uint64_t from = 0;
  uint64_t to = 0;
  std::string client_msg_id;
  std::string text;
  int kind = 1;             // 1=text 2=custom 3=image 4=voice
  nlohmann::json image;     // kind=3 的载荷
  nlohmann::json voice;     // kind=4 的载荷
  nlohmann::json custom;    // kind=2 的载荷
  /// 引用回复(批次 L-2):被引用消息的 id。**只有这一个字段来自客户端** ——
  /// 引用内容(谁说的、说了什么、是否已撤回)一律由服务端回库查并生成快照,
  /// 客户端夹带的 `ref` 载荷在这里根本无处可放。
  std::optional<uint64_t> ref_msg_id;
};

struct SendResult {
  uint64_t msg_id = 0;
  uint64_t seq = 0;
  int64_t ts = 0;
  std::string from_nickname;
  std::string from_avatar;
  /// 刚落库的那一行(含 kind/body/ref_snapshot)。
  ///
  /// 为什么把它带出来:下行 `message` 帧必须与 `/im/api/messages` 用**同一个**
  /// 序列化函数(`frames.h::message_json`),那份函数吃的是 `MessageRow`。
  /// 否则两个构造函数迟早有一边漏字段(引用就是这样漏的)。
  MessageRow row;
};

class MessageService {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造消息服务 绑定各仓库并读慢日志阈值
// 参数说明     pool                  MySQL 连接池
//              users                 用户仓库
//              conversations         会话仓库
//              messages              消息仓库
//              blacklist             黑名单仓库
//              text_max              文本消息最大字符数 默认 2000
//              media_prefix          媒体 URL 前缀 用于规范化图片与语音地址
//              media_sign_secret     媒体签名密钥 交给 MediaSigner
//              media_sign_ttl        媒体签名有效期秒 默认 86400
// 返回参数     void                  无返回值
// 使用示例     MessageService service(pool, users, conversations, messages, blacklist);
// 备注信息     构造只保存引用与配置 不查库 各仓库的生命周期必须长于本对象
//              环境变量 IM_SLOW_SEND_MS 非零时 单条发送超过该毫秒数打一条慢发送日志
//-------------------------------------------------------------------------------------------------------------------
  MessageService(MysqlPool& pool, UserRepo& users, ConversationRepo& conversations,
                 MessageRepo& messages, BlacklistRepo& blacklist,
                 std::size_t text_max = 2000, std::string media_prefix = "",
                 std::string media_sign_secret = "", int media_sign_ttl = 86400);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     发送一条消息 校验后落库并组装下行数据
// 参数说明     request                        发送请求 含收发双方 client_msg_id 类型与载荷
// 返回参数     std::variant<SendResult, int>  成功给刚落库的消息行 失败给业务码 42201 40302 50001
// 使用示例     auto result = service.send(request);
// 备注信息     链路 参数与载荷校验 配对检查 黑名单检查 锁会话取 seq 生成引用快照 落库 更新会话与对端状态 提交后组装下行数据
//              鉴权与发送配额在入口层完成 配额目前只在 WS 发送路径上做 下行帧由入口层按返回值推送
//              1213 死锁与 1205 锁等待超时最多重试 8 次 退避带抖动 用尽回 50001
//              1062 唯一键冲突按幂等重放处理 回已有消息行 已有行的 to 与本次不同则回 42201
//              系统通知 from 为 0 时跳过配对与黑名单检查 也不建发送者用户行
//-------------------------------------------------------------------------------------------------------------------
  std::variant<SendResult, int> send(const SendRequest& request);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     列出我的会话列表并修正被隐藏的摘要
// 参数说明     uid                            请求者账号
//              limit                          最多返回条数
// 返回参数     std::vector<ConversationView>  会话视图 新到旧
// 使用示例     auto views = service.list_conversations(uid, 50);
// 备注信息     只有最后一条可见消息被我隐藏的会话才回查上一条 其余会话零额外查询
//-------------------------------------------------------------------------------------------------------------------
  std::vector<ConversationView> list_conversations(uint64_t uid, int limit);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按会话分页拉取历史消息
// 参数说明     uid                      请求者账号
//              peer                     会话对端
//              before_seq               游标 只取 seq 更小的 0 表示从最新开始
//              limit                    最多返回条数
// 返回参数     std::vector<MessageRow>  消息行 新到旧 会话不存在时返回空
// 使用示例     auto rows = service.list_messages(uid, peer, 0, 30);
// 备注信息     先按 (uid, peer) 查会话 查不到直接返回空 未配对与会话已删都不区分
//-------------------------------------------------------------------------------------------------------------------
  std::vector<MessageRow> list_messages(uint64_t uid, uint64_t peer, uint64_t before_seq,
                                        int limit);
  /// 关键词搜索(口径见 `MessageRepo::search`)。
  ///
  /// Args:
  ///   uid: 请求者账号。
  ///   keyword: 用户关键词。
  ///   before_id: 游标,0 表示第一页。
  ///   limit: 最多返回条数。
  ///
  /// Returns:
  ///   命中的消息行,新 → 旧。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按关键词搜索我的历史消息
// 参数说明     uid                      请求者账号
//              keyword                  用户关键词
//              before_id                游标消息 id 0 表示第一页
//              limit                    最多返回条数
// 返回参数     std::vector<MessageRow>  命中的消息行 新到旧
// 使用示例     auto rows = service.search(uid, "晚饭", 0, 20);
// 备注信息     只搜我参与的会话 匹配口径与游标规则见 MessageRepo::search
//-------------------------------------------------------------------------------------------------------------------
  std::vector<MessageRow> search(uint64_t uid, const std::string& keyword, uint64_t before_id,
                                 int limit);
  /// 把一个会话标到已读,并返回**写完之后**的已读位置(已读回执广播用)。
  ///
  /// Args:
  ///   uid: 读消息的人。
  ///   peer: 会话对端。
  ///   seq: 读到哪;`0` 表示「读到该会话最新」(`last_seq`)。
  ///
  /// Returns:
  ///   成功时返回实库里的 `read_seq`(已 `GREATEST`,不会回退),会话不存在时 `nullopt`。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把会话标到已读并回读真实已读位置
// 参数说明     uid                      读消息的人
//              peer                     会话对端
//              seq                      读到哪 0 表示读到该会话最新
// 返回参数     std::optional<uint64_t>  实库里的 read_seq 会话不存在时 nullopt
// 使用示例     auto read_seq = service.mark_read(uid, peer, seq);
// 备注信息     落库用 GREATEST 乱序到达的旧 read 帧不会让已读回退
//              必须回读实库再广播 直接回传入参会把客户端推回未读
//-------------------------------------------------------------------------------------------------------------------
  std::optional<uint64_t> mark_read(uint64_t uid, uint64_t peer, uint64_t seq);
  /// 设置会话的置顶 / 免打扰(批次 N),返回**回读实库**后的真实标志位。
  ///
  /// 这是**单方**操作:只写 `uid` 自己那一行,不给对端发任何帧(对端不该知道我置顶了谁)。
  /// 也不加 WS 帧 —— 低频写操作走 HTTP,客户端切列表时靠 `GET /im/api/conversations`
  /// 的 `pinned` / `muted` 字段刷新。
  ///
  /// Args:
  ///   uid: 会话主人。
  ///   peer: 会话对端。
  ///   pinned: 置顶开关;`nullopt` = 不改。置顶写当前毫秒,取消写 0,重复置顶不改时间。
  ///   muted: 免打扰开关;`nullopt` = 不改。
  ///
  /// Returns:
  ///   真实标志位;会话不存在(未配对 / 从没聊过)时 `nullopt`,由上层回 404。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置会话置顶与免打扰并回读真实标志
// 参数说明     uid                               会话主人
//              peer                              会话对端
//              pinned                            置顶开关 nullopt 表示不改
//              muted                             免打扰开关 nullopt 表示不改
// 返回参数     std::optional<ConversationFlags>  回读实库后的标志位 会话不存在时 nullopt
// 使用示例     auto flags = service.set_conversation_flags(uid, peer, true, std::nullopt);
// 备注信息     单方操作 只写 uid 自己那一行 不给对端发任何帧
//              置顶写当前毫秒 取消写 0 重复置顶不改时间
//-------------------------------------------------------------------------------------------------------------------
  std::optional<ConversationFlags> set_conversation_flags(uint64_t uid, uint64_t peer,
                                                          std::optional<bool> pinned,
                                                          std::optional<bool> muted);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     撤回自己发出的消息 限 120 秒内
// 参数说明     uid                              请求者账号
//              msg_id                           要撤回的消息 id
// 返回参数     std::variant<RevokeResult, int>  成功给撤回结果 失败给业务码 41001
// 使用示例     auto result = service.revoke(uid, msg_id);
// 备注信息     非本人 已撤回 距发送超过 120000 毫秒三种情形统一回 41001 调用方无法据此判断消息归属
//              撤回只写 revoked_at 不删消息行
//-------------------------------------------------------------------------------------------------------------------
  std::variant<RevokeResult, int> revoke(uint64_t uid, uint64_t msg_id);
  /// 多选删除(批次 T):把一批消息从我这边隐藏掉。
  ///
  /// **单方**语义(与微信一致):只往 `im_message_hidden` 写「我不想再看到」,
  /// 不碰消息本体、不动 `im_conversation.last_seq`、不给对端发任何帧、不可恢复。
  ///
  /// 一个事务里做三件事:
  ///   1. 取「这批 id 里真实存在且我参与」的消息行 —— 别人的 id **静默忽略**
  ///      (回 403/404 会变成「探测别人消息是否存在」的信道);
  ///   2. 逐条 `INSERT IGNORE`,用 `affected_rows` 判断是不是**本次新隐藏**
  ///      (返回值与幂等都建立在这个数上);
  ///   3. 对「新隐藏 + 对端发的 + 尚未读(`seq > 我的 read_seq`)」的条数**按会话减未读**
  ///      —— 未读是计数器,不加这一步就会「删了还占未读」。
  ///
  /// Args:
  ///   uid: 请求者账号。
  ///   ids: 消息 id 列表(调用方已校验:非空、≤ 50、每个都是正整数)。
  ///
  /// Returns:
  ///   本次**新**隐藏的条数;重复删同一批返回 0。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     多选删除 把一批消息从我这边隐藏
// 参数说明     uid             请求者账号
//              ids             消息 id 列表 调用方已校验非空 不超过 50 且都是正整数
// 返回参数     uint64_t        本次新隐藏的条数 重复删同一批返回 0
// 使用示例     const uint64_t hidden = service.hide_messages(uid, ids);
// 备注信息     单方语义 只写 im_message_hidden 不碰消息本体与 last_seq 不给对端发帧 不可恢复
//              别人的 id 静默忽略 不区分不存在与无权
//              减未读只算本次新隐藏 对端发来的 且尚未读的条数 事务异常回滚后重抛
//-------------------------------------------------------------------------------------------------------------------
  uint64_t hide_messages(uint64_t uid, const std::vector<uint64_t>& ids);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     删除我这一侧的会话
// 参数说明     uid             请求者账号
//              peer            会话对端
// 返回参数     bool            会话存在并标记成功返回 true
// 使用示例     if (!service.delete_conversation(uid, peer)) { return 404; }
// 备注信息     只置 deleted 标记 不删消息行 会话不存在返回 false 由上层回 404
//-------------------------------------------------------------------------------------------------------------------
  bool delete_conversation(uint64_t uid, uint64_t peer);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     注销账号并清空该用户的全部 IM 数据
// 参数说明     uid             账号
// 返回参数     bool            全部删除并提交成功返回 true 异常回滚后返回 false
// 使用示例     const bool ok = service.delete_account(uid);
// 备注信息     隐藏行必须先清 消息删掉之后就反查不到 msg_id 隐藏行会变成永久垃圾
//              单事务依次清 隐藏行 消息 会话 黑名单 配对 用户 失败只记日志不抛
//-------------------------------------------------------------------------------------------------------------------
  bool delete_account(uint64_t uid);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     更新用户昵称与头像
// 参数说明     uid             账号
//              nickname        新昵称 nullopt 表示不改
//              avatar          新头像 nullopt 表示不改
// 返回参数     bool            固定返回 true 失败以异常形式抛出
// 使用示例     service.update_profile(uid, std::string("小明"), std::nullopt);
// 备注信息     只写非 nullopt 的字段 内容合法性由调用方校验
//-------------------------------------------------------------------------------------------------------------------
  bool update_profile(uint64_t uid, const std::optional<std::string>& nickname,
                      const std::optional<std::string>& avatar);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把对端加入我的黑名单
// 参数说明     owner           拉黑发起方
//              peer            被拉黑方
// 返回参数     void            无返回值
// 使用示例     service.blacklist_add(owner, peer);
// 备注信息     仓库层自己取连接 数据库异常会向上抛
//-------------------------------------------------------------------------------------------------------------------
  void blacklist_add(uint64_t owner, uint64_t peer);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把对端从我的黑名单移除
// 参数说明     owner           拉黑发起方
//              peer            被拉黑方
// 返回参数     void            无返回值
// 使用示例     service.blacklist_remove(owner, peer);
// 备注信息     只删 owner 到 peer 这一条 不影响对端对我的拉黑
//-------------------------------------------------------------------------------------------------------------------
  void blacklist_remove(uint64_t owner, uint64_t peer);
  /// 配对关系(聊天权限):由 Django 在配对/解除配对/拉黑时同步。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断两个账号是否已配对 复用调用方事务
// 参数说明     lease           调用方已持有的连接租约
//              a               账号 A
//              b               账号 B
// 返回参数     bool            im_pair 里存在这一对时返回 true
// 使用示例     if (!pair_exists(lease, from, to)) { return 40302; }
// 备注信息     im_pair 只存 (小, 大) 有序对 这里先取 min/max 再查
//              复用租约保证与发消息在同一事务内 不会读到并发删除的中间态
//-------------------------------------------------------------------------------------------------------------------
  bool pair_exists(MysqlPool::Lease& lease, uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断两个账号是否已配对 自取连接
// 参数说明     a               账号 A
//              b               账号 B
// 返回参数     bool            im_pair 里存在这一对时返回 true
// 使用示例     const bool paired = service.pair_exists(a, b);
// 备注信息     内部从连接池取一条租约再转调三参版本 口径完全一致
//-------------------------------------------------------------------------------------------------------------------
  bool pair_exists(uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     建立两个账号的配对关系
// 参数说明     a               账号 A
//              b               账号 B
// 返回参数     void            无返回值
// 使用示例     service.pair_add(a, b);
// 备注信息     落库前按 min/max 排序 重复配对靠 ON DUPLICATE KEY 幂等 不改 created_at
//-------------------------------------------------------------------------------------------------------------------
  void pair_add(uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     解除两个账号的配对关系
// 参数说明     a               账号 A
//              b               账号 B
// 返回参数     void            无返回值
// 使用示例     service.pair_remove(a, b);
// 备注信息     同样按 min/max 排序 关系本来不存在时静默成功
//-------------------------------------------------------------------------------------------------------------------
  void pair_remove(uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     探测数据库当前是否可用
// 参数说明     无
// 返回参数     bool            取到连接并执行 SELECT 1 成功返回 true
// 使用示例     if (!service.ready()) { return 503; }
// 备注信息     内部吞掉全部异常只回 bool 供健康检查与启动自检使用
//-------------------------------------------------------------------------------------------------------------------
  bool ready();

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取用户仓库引用
// 参数说明     无
// 返回参数     UserRepo&       用户仓库引用
// 使用示例     auto& repo = service.users();
// 备注信息     直接暴露成员引用 调用方不得在服务对象析构后继续持有
//-------------------------------------------------------------------------------------------------------------------
  UserRepo& users() { return users_; }
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取会话仓库引用
// 参数说明     无
// 返回参数     ConversationRepo&  会话仓库引用
// 使用示例     auto& repo = service.conversations();
// 备注信息     直接暴露成员引用 调用方不得在服务对象析构后继续持有
//-------------------------------------------------------------------------------------------------------------------
  ConversationRepo& conversations() { return conversations_; }
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取消息仓库引用
// 参数说明     无
// 返回参数     MessageRepo&    消息仓库引用
// 使用示例     auto& repo = service.messages();
// 备注信息     直接暴露成员引用 调用方不得在服务对象析构后继续持有
//-------------------------------------------------------------------------------------------------------------------
  MessageRepo& messages() { return messages_; }
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取黑名单仓库引用
// 参数说明     无
// 返回参数     BlacklistRepo&  黑名单仓库引用
// 使用示例     auto& repo = service.blacklist();
// 备注信息     直接暴露成员引用 调用方不得在服务对象析构后继续持有
//-------------------------------------------------------------------------------------------------------------------
  BlacklistRepo& blacklist() { return blacklist_; }
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取媒体签名器只读引用
// 参数说明     无
// 返回参数     const MediaSigner&  媒体签名器
// 使用示例     const auto& signer = service.signer();
// 备注信息     只读 图片与语音 URL 的规范化与现签都走它 密钥与有效期由构造参数决定
//-------------------------------------------------------------------------------------------------------------------
  const MediaSigner& signer() const { return signer_; }

 private:
  MysqlPool& pool_;
  UserRepo& users_;
  ConversationRepo& conversations_;
  MessageRepo& messages_;
  BlacklistRepo& blacklist_;
  std::size_t text_max_;
  std::string media_prefix_;
  MediaSigner signer_;
  int slow_send_ms_ = 0;
};
