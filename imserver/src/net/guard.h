#pragma once
#include <boost/asio/ip/address.hpp>

#include <cstddef>
#include <string>
#include <vector>

/// 入口守卫:监听地址解析、可信代理判定与浏览器 Origin 校验(审计项 L9)。
///
/// 背景:WS 连接默认从 `X-Real-IP` 取客户端 IP 用于「单 IP 连接数」和「鉴权令牌桶」,
/// 一旦 9100 端口被绕过 nginx 直连,这个头就能被伪造,限流形同虚设。这里把「谁有资格
/// 写这个头」收敛成显式的可信代理列表(默认只有回环),并把 Origin 校验从「配了才管」
/// 改成「没配也按同源兜底」。
namespace net_guard {

/// 监听地址 `host:port` 的解析结果。
struct ListenAddr {
  boost::asio::ip::address address;
  unsigned short port = 0;
};

/// 解析 `host:port`(host 支持 IPv4、IPv6 字面量);非法输入抛 `std::invalid_argument`。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     解析 host:port 形式的监听地址
// 参数说明     raw              形如 127.0.0.1:9101 或 [::1]:9100 的串
// 返回参数     ListenAddr       解析出的地址与端口
// 使用示例     const auto listen = net_guard::parse_listen(cfg_.listen_http);
// 备注信息     host 支持 IPv4 与 IPv6 字面量 端口必须落在 0..65535 非法输入抛 std::invalid_argument
//-------------------------------------------------------------------------------------------------------------------
ListenAddr parse_listen(const std::string& raw);

/// 是否为回环地址(`127.0.0.0/8` 与 `::1`)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判定地址是否为回环地址
// 参数说明     address          待判定的对端地址
// 返回参数     bool             是回环地址返回 true
// 使用示例     if (net_guard::is_loopback(peer_addr)) { /* 只允许本机 */ }
// 备注信息     覆盖 127.0.0.0/8 与 ::1 启动时的监听地址校验与 /metrics 的放行都依赖它
//-------------------------------------------------------------------------------------------------------------------
bool is_loopback(const boost::asio::ip::address& address);

/// 可信代理网段表。只有直连对端命中这里的地址,才采信它带来的 `X-Real-IP`。
class ProxyTrust {
 public:
  /// 默认策略:只信任本机(容器 `network_mode: host` + nginx 反代即属此类)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造只信任本机的默认代理表
// 参数说明     无
// 返回参数     ProxyTrust       含 127.0.0.1/32 与 ::1/128 两条规则
// 使用示例     auto trust = net_guard::ProxyTrust::loopback_only();
// 备注信息     容器 network_mode: host 加同机 nginx 反代即属此类 也是未配置时的默认策略
//-------------------------------------------------------------------------------------------------------------------
  static ProxyTrust loopback_only();

  /// 从配置项解析,支持单个 IP 与 CIDR(`10.0.0.0/8`、`fd00::/8`);
  /// 任何一项非法都抛 `std::invalid_argument`(宁可启动失败,也不静默放宽)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     从配置项解析可信代理网段表
// 参数说明     entries          形如 127.0.0.1 或 10.0.0.0/8 的条目列表 空串跳过
// 返回参数     ProxyTrust       解析后的规则表
// 使用示例     auto allow = net_guard::ProxyTrust::from_list(cfg.internal_allow);
// 备注信息     单个 IP 与 CIDR 都支持 IPv4 / IPv6 均可
//              任一条目非法即抛 std::invalid_argument 宁可启动失败也不静默放宽
//-------------------------------------------------------------------------------------------------------------------
  static ProxyTrust from_list(const std::vector<std::string>& entries);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判定直连对端是否命中可信代理表
// 参数说明     peer             直连对端地址
// 返回参数     bool             命中任一规则返回 true
// 使用示例     if (trust.trusted(peer_addr)) { /* 可以采信 X-Real-IP */ }
// 备注信息     比对前先把 IPv4-mapped IPv6 归一成 IPv4 规则表因此只需写一份
//-------------------------------------------------------------------------------------------------------------------
  bool trusted(const boost::asio::ip::address& peer) const;

  /// 规则条数(启动日志与测试用)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     返回可信代理规则条数
// 参数说明     无
// 返回参数     std::size_t      规则条数
// 使用示例     trust.size();
// 备注信息     只给启动日志与测试用 无副作用 不参与判定
//-------------------------------------------------------------------------------------------------------------------
  std::size_t size() const { return rules_.size(); }

 private:
  struct Rule {
    boost::asio::ip::address base;
    int bits = 0;
  };

  std::vector<Rule> rules_;
};

/// 计算客户端 IP:对端可信且头里是合法单 IP 时采用该头,否则一律用对端地址。
///
/// 头里出现逗号(多级代理拼接)、空白或非 IP 文本时同样回退到对端地址,避免把
/// 伪造串塞进限流 key。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     计算用于限流的客户端 IP
// 参数说明     peer             直连对端地址
//              real_ip_header     X-Real-IP 头的原始值 可为空
//              trust            可信代理表
// 返回参数     std::string      客户端 IP 文本
// 使用示例     const auto ip = net_guard::client_ip(peer, header, trust);
// 备注信息     只有对端命中可信代理且头里是合法单 IP 时才采信该头
//              头里含逗号 空白或非 IP 文本一律回退到对端地址 避免伪造串进限流 key
//-------------------------------------------------------------------------------------------------------------------
std::string client_ip(const boost::asio::ip::address& peer, const std::string& real_ip_header,
                      const ProxyTrust& trust);

/// 浏览器 WS 的 Origin 校验。
///
/// - 没有 `Origin`(原生 App、压测脚本)→ 放行;
/// - 配置了 `IM_ALLOWED_ORIGINS` → 必须在白名单内(忽略大小写与结尾 `/`);
/// - 未配置白名单 → 退化为同源校验:`Origin` 的 host[:port] 必须等于 `Host` 头。
///
/// 同源比较只比 authority(host + 非默认端口),不比较 scheme —— `Host` 头里没有
/// scheme,强行比较会把正常请求误杀。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     校验浏览器 WebSocket 握手的 Origin
// 参数说明     origin           Origin 头的原始值 空串表示没发
//              host             Host 头的原始值
//              allowed          IM_ALLOWED_ORIGINS 白名单 为空表示未配置
// 返回参数     bool             放行返回 true
// 使用示例     if (!net_guard::origin_allowed(origin, host, cfg.allowed_origins)) { /* 拒绝握手 */ }
// 备注信息     没有 Origin 直接放行 原生 App 与压测脚本都不发这个头
//              配了白名单必须命中 未配置则退化为同源比较 只比 host 与非默认端口 不比 scheme
//-------------------------------------------------------------------------------------------------------------------
bool origin_allowed(const std::string& origin, const std::string& host,
                    const std::vector<std::string>& allowed);

}  // namespace net_guard
