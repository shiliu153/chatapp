class IpCounter {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造单 IP 连接数与鉴权限流计数器
// 参数说明     max_per_ip       单 IP 并发连接上限 默认 20
//              auth_rate        鉴权令牌桶速率 每秒 默认 1.0
//              auth_burst       鉴权令牌桶突发上限 默认 60.0
//              max_auth_buckets     鉴权桶数量上限 默认 20000
// 返回参数     void             无返回值
// 使用示例     IpCounter counter(20, 1.0, 60.0);
// 备注信息     只保存参数 计数与令牌桶都在成员里 构造完即可被多个 IO 线程并发调用
//-------------------------------------------------------------------------------------------------------------------
  explicit IpCounter(int max_per_ip = 20, double auth_rate = 1.0, double auth_burst = 60.0,
                     std::size_t max_auth_buckets = 20000)
      : max_(max_per_ip),
        auth_rate_(auth_rate),
        auth_burst_(auth_burst),
        max_auth_buckets_(max_auth_buckets) {}
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     占用一个单 IP 并发连接名额
// 参数说明     ip               客户端 IP 文本
// 返回参数     bool             未达上限并计数成功返回 true
// 使用示例     if (!counter.acquire(ip)) { reject_http(429, "too many connections"); }
// 备注信息     加锁计数 返回 true 后必须配对调用 release 否则名额泄漏
//-------------------------------------------------------------------------------------------------------------------
  bool acquire(const std::string& ip);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     归还一个单 IP 并发连接名额
// 参数说明     ip               客户端 IP 文本
// 返回参数     void             无返回值
// 使用示例     counter.release(ip);
// 备注信息     计数归零时删除该 IP 条目 避免 map 随历史 IP 无限增长 未 acquire 过也安全
//-------------------------------------------------------------------------------------------------------------------
  void release(const std::string& ip);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按 IP 消耗一个鉴权令牌
// 参数说明     ip               客户端 IP 文本
//              now_ms           当前墙钟毫秒
// 返回参数     bool             令牌桶放行返回 true
// 使用示例     if (!counter.allow_auth(ip, now_ms())) { send_raw(error_frame(42901, "认证过于频繁")); }
// 备注信息     桶数达上限先淘汰 10 分钟未活跃的桶 仍满则整体清空 只丢一个限流窗口
//-------------------------------------------------------------------------------------------------------------------
  bool allow_auth(const std::string& ip, int64_t now_ms);
  /// 鉴权令牌桶的当前条数(观测与测试用;正常应远小于上限)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读当前鉴权桶数量
// 参数说明     无
// 返回参数     std::size_t      auth_buckets_ 的条数
// 使用示例     const std::size_t n = counter.auth_bucket_count();
// 备注信息     观测与测试用 加锁读取 正常应远小于上限
//-------------------------------------------------------------------------------------------------------------------
  std::size_t auth_bucket_count() const;

 private:
  /// 令牌桶 + 最后活跃时间:满了先淘汰 10 分钟没动静的桶,再不行整体清空。
  struct AuthBucket {
    TokenBucket bucket;
    int64_t seen_ms = 0;
  };

  const int max_;
  const double auth_rate_;
  const double auth_burst_;
  const std::size_t max_auth_buckets_;
  mutable std::mutex mutex_;
  std::unordered_map<std::string, int> counts_;
  std::unordered_map<std::string, AuthBucket> auth_buckets_;
};

class WsSession : public std::enable_shared_from_this<WsSession> {
 public:
  using tcp = boost::asio::ip::tcp;
  using WsStream = boost::beast::websocket::stream<boost::beast::tcp_stream>;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造一条 WS 会话
// 参数说明     socket           已 accept 的 TCP 连接
//              cfg              配置副本 会话内不再读环境变量
//              registry         会话注册表 负责注册与多端扇出
//              redis            Redis 客户端 用于在线键与发送配额
//              ip_counter       进程级单 IP 计数器
//              messages         消息服务 负责落库与鉴权相关查询
//              push             离线新消息推送器
//              db_pool          DB 线程池 所有碰库任务丢这里
//              trust            可信代理表 决定是否采信 X-Real-IP
//              sensitive        聊天文字敏感词匹配器
// 返回参数     void             无返回值
// 使用示例     WsSession session(std::move(socket), cfg, registry, redis, ip_counter, messages, push, db_pool, trust, sensitive);
// 备注信息     构造不发包 只初始化成员与两个定时器 真正的握手在 run 里发起
//-------------------------------------------------------------------------------------------------------------------
  WsSession(tcp::socket socket, const Config& cfg, SessionRegistry& registry,
            RedisClient& redis, IpCounter& ip_counter, MessageService& messages,
            PushNotifier& push, boost::asio::thread_pool& db_pool,
            const net_guard::ProxyTrust& trust, const sensitive::Matcher& sensitive);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     发起 WS 握手请求的异步读
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     session->run();
// 备注信息     先按 HTTP 读完 upgrade 请求 才能校验 Origin 与 X-Real-IP 再升级
//-------------------------------------------------------------------------------------------------------------------
  void run();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     下发 kicked 帧并关闭连接
// 参数说明     reason           踢下线原因 原样放进 kicked 帧
// 返回参数     void             无返回值
// 使用示例     session->kick("账号已在其他设备登录");
// 备注信息     投递到会话 IO 线程执行 幂等 已关闭的会话直接返回 关闭码固定 4001
//-------------------------------------------------------------------------------------------------------------------
  void kick(const std::string& reason);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     线程安全地投递一帧到发送队列
// 参数说明     frame            已序列化的 JSON 帧文本
// 返回参数     void             无返回值
// 使用示例     send_raw(error_frame(42201, "帧格式错误"));
// 备注信息     任意线程可调 内部 post 到会话 IO 线程;队列超 64 帧或 128KB 以 4004 关闭连接
//-------------------------------------------------------------------------------------------------------------------
  void send_raw(std::string frame);

 private:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     握手请求读完后的入口校验与升级
// 参数说明     ec               读错误码
//              bytes            读到的字节数 未使用
// 返回参数     void             无返回值
// 使用示例     self->on_http_read(ec, bytes);
// 备注信息     依次校验 Origin 与单 IP 连接数 通过后设置帧长上限并 async_accept 升级
//-------------------------------------------------------------------------------------------------------------------
  void on_http_read(boost::beast::error_code ec, std::size_t bytes);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     升级完成后的会话初始化
// 参数说明     ec               升级错误码
// 返回参数     void             无返回值
// 使用示例     self->on_accept(error);
// 备注信息     失败时归还 IP 名额;成功则记录活跃时间 启动鉴权与空闲定时器 进入读循环
//-------------------------------------------------------------------------------------------------------------------
  void on_accept(boost::beast::error_code ec);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     发起下一次 WebSocket 读
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     do_read();
// 备注信息     已进入关闭流程则不再发起 每次读完由 on_read 续接
//-------------------------------------------------------------------------------------------------------------------
  void do_read();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     处理读完的一帧并继续读
// 参数说明     ec               读错误码
//              bytes            读到的字节数 未使用
// 返回参数     void             无返回值
// 使用示例     self->on_read(ec, bytes);
// 备注信息     刷新活跃时间与在线键 解析失败回 42201 但不中断连接
//-------------------------------------------------------------------------------------------------------------------
  void on_read(boost::beast::error_code ec, std::size_t bytes);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按 type 分发单个上行帧
// 参数说明     payload          帧的原始 JSON 文本
// 返回参数     void             无返回值
// 使用示例     on_frame(payload);
// 备注信息     先校验 v 为 1;未鉴权时只接受 auth 帧 其余回 40001 并以 4002 关闭;未知类型回 42201
//-------------------------------------------------------------------------------------------------------------------
  void on_frame(const std::string& payload);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     校验 token 并建立已鉴权会话
// 参数说明     frame            auth 帧
// 返回参数     void             无返回值
// 使用示例     handle_auth(frame);
// 备注信息     依次做 IP 鉴权限流 令牌验签 封禁检查 会话版本比对 任一失败回错误帧并以 4002 或 4003 关闭
//-------------------------------------------------------------------------------------------------------------------
  void handle_auth(const nlohmann::json& frame);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     解析 send 帧并异步提交发送
// 参数说明     frame            send 帧
// 返回参数     void             无返回值
// 使用示例     handle_send(frame);
// 备注信息     先过单连接令牌桶 20 每秒突发 40 与跨连接每分钟配额;文本查敏感词;贴纸只放行 sticker_ 加两位数字;引用只认 ref_msg_id 数字
//-------------------------------------------------------------------------------------------------------------------
  void handle_send(const nlohmann::json& frame);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     处理已读回执并广播
// 参数说明     frame            read 帧
// 返回参数     void             无返回值
// 使用示例     handle_read(frame);
// 备注信息     2 每秒突发 30 限流 超限静默丢弃;落库后向对端推 read 帧 向本人其他端推 self_read 帧
//-------------------------------------------------------------------------------------------------------------------
  void handle_read(const nlohmann::json& frame);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     转发输入中状态
// 参数说明     frame            typing 帧
// 返回参数     void             无返回值
// 使用示例     handle_typing(frame);
// 备注信息     可丢信号 0.5 每秒突发 3;限流 to 非法 发给自己 未配对一律静默丢弃 不回任何错误帧
//-------------------------------------------------------------------------------------------------------------------
  void handle_typing(const nlohmann::json& frame);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     处理消息撤回
// 参数说明     frame            revoke 帧
// 返回参数     void             无返回值
// 使用示例     handle_revoke(frame);
// 备注信息     按 uid 校验归属后向双方扇出 revoked 帧 再回 ack;参数错误回 41001
//-------------------------------------------------------------------------------------------------------------------
  void handle_revoke(const nlohmann::json& frame);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     处理单方会话删除
// 参数说明     frame            conversation_delete 帧
// 返回参数     void             无返回值
// 使用示例     handle_delete(frame);
// 备注信息     按 uid 软删 只删自己那一份;成功后只通知本人其他端 绝不通知对方
//-------------------------------------------------------------------------------------------------------------------
  void handle_delete(const nlohmann::json& frame);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把发送结果写回客户端
// 参数说明     result           成功结果或业务错误码
//              request          原始发送请求 用于回 ack 与离线推送
// 返回参数     void             无返回值
// 使用示例     self->on_send_result(result, request);
// 备注信息     对端不在线才入队离线推送 推送不阻塞 ack;错误码 40302 42201 42901 各有文案
//-------------------------------------------------------------------------------------------------------------------
  void on_send_result(const std::variant<SendResult, int>& result,
                      const SendRequest& request);
  /// 把一段会碰数据库的任务丢进 DB 线程池,并吞掉异常(避免 std::terminate)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把碰库任务丢进 DB 线程池
// 参数说明     task             在 DB 线程里执行的任务
// 返回参数     void             无返回值
// 使用示例     run_db([self, request] { self->messages_.send(request); });
// 备注信息     捕获异常转 50001 下发 避免异常穿出线程池导致 std::terminate
//-------------------------------------------------------------------------------------------------------------------
  void run_db(std::function<void()> task);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     序列化 JSON 对象后下发
// 参数说明     payload          JSON 文本
// 返回参数     void             无返回值
// 使用示例     send_json(nlohmann::json{{"type", "pong"}}.dump());
// 备注信息     仅保留声明 当前实现与调用点都走 send_raw
//-------------------------------------------------------------------------------------------------------------------
  void send_json(const std::string& payload);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     串行写出发送队列的队首
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     do_write();
// 备注信息     已在写或已关闭直接返回;队列空且有待关闭码时执行关闭;单写者模型靠 writing_ 去重
//-------------------------------------------------------------------------------------------------------------------
  void do_write();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     一帧写完后的收尾与续写
// 参数说明     ec               写错误码
//              bytes            写出的字节数 未使用
// 返回参数     void             无返回值
// 使用示例     self->on_write(ec, bytes);
// 备注信息     写失败按 1000 关闭;成功则扣减队列字节数 弹出队首 队列空且有待关闭码时关闭
//-------------------------------------------------------------------------------------------------------------------
  void on_write(boost::beast::error_code ec, std::size_t bytes);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     发起 WebSocket 关闭握手
// 参数说明     code             关闭码 1000 正常 4001 被踢 4002 鉴权失败 4003 封禁 4004 队列溢出
// 返回参数     void             无返回值
// 使用示例     do_close(1000);
// 备注信息     幂等 关闭前取消鉴权与空闲定时器 关闭回调统一走 on_close
//-------------------------------------------------------------------------------------------------------------------
  void do_close(int code);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     连接关闭后的资源清理
// 参数说明     ec               关闭错误码 未使用
// 返回参数     void             无返回值
// 使用示例     self->on_close(ec);
// 备注信息     归还 IP 名额 注销会话;只有该账号最后一个连接关掉才删 Redis 在线键 避免多端互相误标离线
//-------------------------------------------------------------------------------------------------------------------
  void on_close(boost::beast::error_code ec);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     用 HTTP 响应拒绝握手
// 参数说明     status           HTTP 状态码 403 或 429
//              message          错误文案
// 返回参数     void             无返回值
// 使用示例     reject_http(403, "origin not allowed");
// 备注信息     403 对应业务码 40301 其余按 42901;写完响应即关 socket 并归还 IP 名额
//-------------------------------------------------------------------------------------------------------------------
  void reject_http(int status, const std::string& message);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     启动 5 秒鉴权超时定时器
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     arm_auth_timer();
// 备注信息     超时仍未鉴权则回 40001 并以 4002 关闭;鉴权成功时定时器被 cancel
//-------------------------------------------------------------------------------------------------------------------
  void arm_auth_timer();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     启动 15 秒空闲检查定时器
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     arm_idle_timer();
// 备注信息     超过 75 秒没有上行帧按 1000 关闭;已鉴权时顺带刷新在线键 检查完自动续期
//-------------------------------------------------------------------------------------------------------------------
  void arm_idle_timer();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     刷新 Redis 在线键
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     refresh_online();
// 备注信息     30 秒节流 避免每帧都写 Redis 变成全局串行点;未鉴权直接返回
//-------------------------------------------------------------------------------------------------------------------
  void refresh_online();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     校验单账号每分钟发送配额
// 参数说明     now_ms           当前墙钟毫秒 用于取分钟键
// 返回参数     bool             未超配额返回 true
// 使用示例     if (!allow_send_quota(now_ms())) { send_raw(error_frame(42901, "发送过快")); }
// 备注信息     Redis INCR 计数 键按 uid 加分钟 跨连接共享 首次写入 TTL 120 秒;Redis 故障放行 由单连接令牌桶兜底
//-------------------------------------------------------------------------------------------------------------------
  bool allow_send_quota(int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取客户端真实 IP
// 参数说明     无
// 返回参数     std::string      IP 文本 取不到对端时返回 unknown
// 使用示例     const std::string ip = remote_ip();
// 备注信息     只有直连对端命中可信代理表才采信 X-Real-IP 否则用对端地址
//-------------------------------------------------------------------------------------------------------------------
  std::string remote_ip();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     校验握手 Origin
// 参数说明     无
// 返回参数     bool             允许该来源返回 true
// 使用示例     if (!origin_allowed()) { reject_http(403, "origin not allowed"); }
// 备注信息     配了 IM_ALLOWED_ORIGINS 按白名单 未配按同源兜底 无 Origin 的原生端仍放行
//-------------------------------------------------------------------------------------------------------------------
  bool origin_allowed() const;
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     归还单 IP 连接名额
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     release_ip();
// 备注信息     幂等 只有 acquire 成功过才真正释放 断连 拒绝握手 读错误三处共用
//-------------------------------------------------------------------------------------------------------------------
  void release_ip();

  WsStream ws_;
  boost::beast::flat_buffer buffer_;
  boost::beast::http::request<boost::beast::http::string_body> request_;
  std::deque<std::string> outbox_;
  std::size_t outbox_bytes_ = 0;
  bool authed_ = false;
  bool writing_ = false;
  bool closing_ = false;
  bool released_ip_ = false;
  bool ip_acquired_ = false;
  std::optional<int> close_code_;
  uint64_t uid_ = 0;
  /// 端类型(多端在线 K-2):来自 token 的 `ct` claim,鉴权前为空串。
  std::string client_type_;
  std::string client_ip_;
  Config cfg_;
  SessionRegistry& registry_;
  RedisClient& redis_;
  IpCounter& ip_counter_;
  MessageService& messages_;
  /// 离线新消息推送(C-1);`IM_PUSH_URL` 没配时是空壳,调用无副作用。
  PushNotifier& push_;
  boost::asio::thread_pool& db_pool_;
  /// 只有直连对端命中这份表,才采信它带来的 X-Real-IP(L9)。
  const net_guard::ProxyTrust& trust_;
  /// 聊天文字敏感词匹配器(批次 Q):进程级只读,所有会话共享。
  const sensitive::Matcher& sensitive_;
  boost::asio::steady_timer auth_timer_;
  boost::asio::steady_timer idle_timer_;
  std::chrono::steady_clock::time_point last_frame_;
  int64_t last_online_ms_ = 0;
  TokenBucket send_bucket_{20, 40};
  /// 已读回执帧的令牌桶(2/s、突发 30):每次 read 都会给对端推一帧,必须限流。
  TokenBucket read_bucket_{2, 30};
  /// 输入中状态的令牌桶(0.5/s = 1 次 / 2 秒、突发 3),批次 L-1。
  ///
  /// 客户端自己也有 3 秒节流,但那只省流量 —— 客户端可以被改、可以伪造,
  /// 服务端这一层才是防洪泛的那层。超限**静默丢弃**,不回 42901。
  TokenBucket typing_bucket_{0.5, 3};
};

class WsServer {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造 WS 监听器
// 参数说明     io               IO 上下文
//              cfg              配置副本
//              registry         会话注册表
//              redis            Redis 客户端
//              messages         消息服务
//              push             离线推送器
//              db_pool          DB 线程池
// 返回参数     void             无返回值
// 使用示例     WsServer server(io, cfg, registry, redis, messages, push, db_pool);
// 备注信息     构造时按配置建单 IP 计数器与可信代理表 并加载敏感词表;词表改动需重启容器生效
//-------------------------------------------------------------------------------------------------------------------
  WsServer(boost::asio::io_context& io, const Config& cfg, SessionRegistry& registry,
           RedisClient& redis, MessageService& messages, PushNotifier& push,
           boost::asio::thread_pool& db_pool);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     绑定并监听 WS 端口
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     server.start();
// 备注信息     地址取自 IM_LISTEN_WS 默认 127.0.0.1:9100 开启 reuse_address 后进入 accept 循环
//-------------------------------------------------------------------------------------------------------------------
  void start();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     关闭 WS 监听端口
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     server.stop();
// 备注信息     只停 accept 已建立的会话由 io_context 停止后自然结束
//-------------------------------------------------------------------------------------------------------------------
  void stop();

 private:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     异步接受下一个连接
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     do_accept();
// 备注信息     每个连接建在独立 strand 上;acceptor 关闭后立即返回 否则递归续接
//-------------------------------------------------------------------------------------------------------------------
  void do_accept();

  boost::asio::io_context& io_;
  boost::asio::ip::tcp::acceptor acceptor_;
  Config cfg_;
  SessionRegistry& registry_;
  RedisClient& redis_;
  MessageService& messages_;
  PushNotifier& push_;
  boost::asio::thread_pool& db_pool_;
  IpCounter ip_counter_;
  /// 进程级可信代理表,所有会话共享(只读)。
  net_guard::ProxyTrust trust_;
  /// 聊天文字敏感词表(批次 Q):启动时构建一次,之后所有会话只读共享。
  sensitive::Matcher sensitive_;
};
