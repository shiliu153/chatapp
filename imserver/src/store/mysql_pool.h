#pragma once
#include <mysql/mysql.h>

#include <chrono>
#include <condition_variable>
#include <cstdint>
#include <mutex>
#include <string>
#include <vector>

#include "config.h"

class MysqlPool {
 public:
  class Lease {
   public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造连接租约 接管一条已借出的连接
// 参数说明     pool             所属连接池 用于归还
//              conn             借出的 MYSQL 连接 允许为空
// 返回参数     void             无返回值
// 使用示例     MysqlPool::Lease lease(pool, conn);
// 备注信息     构造后连接归租约独占 析构自动归还 调用方不要再 mysql_close
//-------------------------------------------------------------------------------------------------------------------
    Lease(MysqlPool& pool, MYSQL* conn);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     析构租约 把连接归还连接池
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     { auto lease = pool.acquire(); }  // 离开作用域即归还
// 备注信息     归还走 MysqlPool::release 池已关闭时直接关闭连接 析构不抛异常
//-------------------------------------------------------------------------------------------------------------------
    ~Lease();
    Lease(const Lease&) = delete;
    Lease& operator=(const Lease&) = delete;
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     移动构造 转移连接所有权
// 参数说明     other            源租约 转移后其 pool_ 与 conn_ 置空
// 返回参数     void             无返回值
// 使用示例     MysqlPool::Lease moved(std::move(lease));
// 备注信息     禁止拷贝 保证一条连接只有一个持有者 源对象析构不再归还
//-------------------------------------------------------------------------------------------------------------------
    Lease(Lease&& other) noexcept;
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     移动赋值 先归还自身再接管对方连接
// 参数说明     other            源租约 转移后置空
// 返回参数     Lease&           返回 *this
// 使用示例     lease = pool.acquire();
// 备注信息     有自赋值保护 赋值前先 release() 归还当前连接 异常规格 noexcept
//-------------------------------------------------------------------------------------------------------------------
    Lease& operator=(Lease&& other) noexcept;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取裸连接指针 供 Stmt 与预编译语句使用
// 参数说明     无
// 返回参数     MYSQL*           连接指针 池耗尽且重连失败时为空
// 使用示例     Stmt stmt(lease.get(), sql);
// 备注信息     不转移所有权 返回空指针时构造 Stmt 会抛 MysqlError
//-------------------------------------------------------------------------------------------------------------------
    MYSQL* get() const { return conn_; }
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     执行非预编译 SQL 并返回结果集
// 参数说明     sql              完整 SQL 文本 含已拼接的字面量
// 返回参数     MYSQL_RES*       结果集 调用方负责 mysql_free_result
// 使用示例     MYSQL_RES* res = lease.query("SELECT 1");
// 备注信息     连接级错误 2006/2013/2055 会先丢弃该连接再抛 MysqlError 连接为空抛 2006
//-------------------------------------------------------------------------------------------------------------------
    MYSQL_RES* query(const std::string& sql);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     转义字符串 供拼 SQL 字面量
// 参数说明     input            原始字符串 可含引号与反斜杠
// 返回参数     std::string      已转义文本
// 使用示例     std::string lit = "'" + lease.escape(ct) + "'";
// 备注信息     走 mysql_real_escape_string 连接为空抛 MysqlError(2006) 能参数化就别用本方法
//-------------------------------------------------------------------------------------------------------------------
    std::string escape(const std::string& input) const;
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     开启事务
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     lease.begin();
// 备注信息     等价执行 START TRANSACTION 失败抛 MysqlError 必须与 commit/rollback 配对
//-------------------------------------------------------------------------------------------------------------------
    void begin();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     提交当前事务
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     lease.commit();
// 备注信息     无活动事务时 MySQL 静默成功 失败抛 MysqlError
//-------------------------------------------------------------------------------------------------------------------
    void commit();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     回滚当前事务
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     lease.rollback();
// 备注信息     异常路径也要调用 无活动事务时 MySQL 静默成功
//-------------------------------------------------------------------------------------------------------------------
    void rollback();

   private:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     归还连接并清空自身指针
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     release();  // 仅在类内部调用
// 备注信息     幂等 重复调用不会二次归还 归还后 get() 返回空指针
//-------------------------------------------------------------------------------------------------------------------
    void release();

    MysqlPool* pool_ = nullptr;
    MYSQL* conn_ = nullptr;
  };

  /// 建池。
  ///
  /// Args:
  ///   dsn: MySQL 连接串。
  ///   size: 连接数(启动时全部建好,连不上直接抛,属于配置错误)。
  ///   idle_ping_ms: 连接空闲超过该毫秒数就先 ping 一次再交给调用方;
  ///     0 表示每次都 ping(测试用),负数表示关闭探测。
  ///   connect_wait_ms: 启动时连不上 MySQL 的最长等待毫秒数;0 = 首次失败立即抛。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造连接池 启动时建满全部连接
// 参数说明     dsn                 MySQL 连接参数 主机 端口 账号 口令 库名
//              size                连接数 小于等于 0 抛 std::invalid_argument
//              idle_ping_ms        空闲超过该毫秒数先 ping 一次 0 表示每次都 ping 负数关闭探测
//              connect_wait_ms     启动连不上 MySQL 的最长等待毫秒数 0 表示首次失败立即抛
// 返回参数     void             无返回值
// 使用示例     MysqlPool pool(dsn, 8, 5000, 30000);
// 备注信息     窗口内按 2 秒间隔重试 超窗口抛 std::runtime_error 中途失败会关掉已建连接
//-------------------------------------------------------------------------------------------------------------------
  MysqlPool(const MysqlDsn& dsn, int size, int64_t idle_ping_ms = 5000,
            int64_t connect_wait_ms = 0);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     析构连接池 关闭全部空闲连接
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     { MysqlPool pool(dsn, 4); }  // 离开作用域关闭连接
// 备注信息     置 closed_ 并唤醒等待者 仍借出未还的租约在归还时才关闭 需先停掉工作线程
//-------------------------------------------------------------------------------------------------------------------
  ~MysqlPool();
  MysqlPool(const MysqlPool&) = delete;
  MysqlPool& operator=(const MysqlPool&) = delete;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     借出一条连接 无空闲时阻塞等待
// 参数说明     无
// 返回参数     Lease            独占的连接租约
// 使用示例     auto lease = pool.acquire();
// 备注信息     池已关闭抛 std::runtime_error 空闲超阈值先 ping 失败则重连 重连彻底失败返回空连接
//-------------------------------------------------------------------------------------------------------------------
  Lease acquire();

 private:
  struct Slot {
    MYSQL* conn = nullptr;
    int64_t last_used_ms = 0;
  };

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把连接放回空闲队列
// 参数说明     conn             要归还的连接 允许为空
// 返回参数     void             无返回值
// 使用示例     release(conn);  // 仅由 Lease 归还时调用
// 备注信息     池已关闭则就地 mysql_close 否则入队并 notify_one
//-------------------------------------------------------------------------------------------------------------------
  void release(MYSQL* conn);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     销毁不可用连接
// 参数说明     conn             要关闭的连接 允许为空
// 返回参数     void             无返回值
// 使用示例     discard(conn);
// 备注信息     先 clear_stmt_cache 再 mysql_close 不还池 下一次 acquire 重新建连
//-------------------------------------------------------------------------------------------------------------------
  void discard(MYSQL* conn);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     有限次重连 失败返回空指针
// 参数说明     attempts         最大尝试次数
// 返回参数     MYSQL*           新连接 全部失败返回 nullptr
// 使用示例     MYSQL* conn = pool.connect_with_retry(3);
// 备注信息     每次失败按 50*(n+1) 毫秒退避 不抛异常 空连接让后续 SQL 走 2006 分支
//-------------------------------------------------------------------------------------------------------------------
  MYSQL* connect_with_retry(int attempts);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在截止时间前反复重连
// 参数说明     deadline         steady_clock 截止时刻
// 返回参数     MYSQL*           新连接 超过截止时间抛 std::runtime_error
// 使用示例     connect_until(std::chrono::steady_clock::now() + std::chrono::seconds(30));
// 备注信息     每 2 秒重试一次 用于启动时等待 DB 就绪 失败信息带尝试次数
//-------------------------------------------------------------------------------------------------------------------
  MYSQL* connect_until(std::chrono::steady_clock::time_point deadline);

  MysqlDsn dsn_;
  int64_t idle_ping_ms_ = 5000;
  int64_t connect_wait_ms_ = 0;
  std::mutex mutex_;
  std::condition_variable cv_;
  std::vector<Slot> idle_;
  int size_ = 0;
  bool closed_ = false;
};
