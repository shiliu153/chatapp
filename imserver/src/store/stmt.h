#pragma once
#include <mysql/mysql.h>

#include <stdexcept>
#include <string>
#include <vector>

class MysqlError : public std::runtime_error {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造带 MySQL 错误码的异常
// 参数说明     code             MySQL errno 0 表示客户端侧失败
//              message          错误描述
// 返回参数     void             无返回值
// 使用示例     throw MysqlError(2006, "mysql lease has no live connection");
// 备注信息     同时携带 what() 文本与 code() 整数 供上层分流 50001 分支
//-------------------------------------------------------------------------------------------------------------------
  MysqlError(int code, const std::string& message) : std::runtime_error(message), code_(code) {}
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取 MySQL 错误码
// 参数说明     无
// 返回参数     int              errno 数值
// 使用示例     int code = error.code();
// 备注信息     0 表示非服务端错误 例如 mysql_stmt_init 失败
//-------------------------------------------------------------------------------------------------------------------
  int code() const { return code_; }

 private:
  int code_;
};

/// 关闭某条连接上缓存的所有 prepared statement(连接销毁前调用)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     关闭某条连接上缓存的所有 prepared statement
// 参数说明     conn             即将销毁的连接
// 返回参数     void             无返回值
// 使用示例     clear_stmt_cache(lease.get());
// 备注信息     连接销毁前必须调用 否则缓存的 MYSQL_STMT 泄漏 幂等
//-------------------------------------------------------------------------------------------------------------------
void clear_stmt_cache(MYSQL* conn);

class Stmt {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造预编译语句 命中缓存则复用
// 参数说明     conn             独占使用的连接
//              sql              带 ? 占位符的 SQL
// 返回参数     void             无返回值
// 使用示例     Stmt stmt(lease.get(), "DELETE FROM im_user WHERE user_id=?");
// 备注信息     prepare 失败抛 MysqlError 同一 (连接,SQL) 只 prepare 一次
//-------------------------------------------------------------------------------------------------------------------
  Stmt(MYSQL* conn, const std::string& sql);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     析构语句对象 不关闭底层 statement
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     { Stmt stmt(conn, sql); }
// 备注信息     底层 MYSQL_STMT 归全局缓存所有 由 clear_stmt_cache 统一关闭
//-------------------------------------------------------------------------------------------------------------------
  ~Stmt();
  Stmt(const Stmt&) = delete;
  Stmt& operator=(const Stmt&) = delete;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     绑定无符号 64 位整数参数
// 参数说明     index            从 0 开始的占位符序号
//              value            参数值
// 返回参数     void             无返回值
// 使用示例     stmt.bind_uint(0, uid);
// 备注信息     按 MYSQL_TYPE_LONGLONG 加 is_unsigned 绑定 缓冲区指向对象内部存储
//-------------------------------------------------------------------------------------------------------------------
  void bind_uint(int index, uint64_t value);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     绑定有符号 32 位整数参数
// 参数说明     index            从 0 开始的占位符序号
//              value            参数值
// 返回参数     void             无返回值
// 使用示例     stmt.bind_int(0, level);
// 备注信息     按 MYSQL_TYPE_LONG 绑定 缓冲区指向对象内部存储
//-------------------------------------------------------------------------------------------------------------------
  void bind_int(int index, int value);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     绑定字符串参数
// 参数说明     index            从 0 开始的占位符序号
//              value            参数值 按字节长度传
// 返回参数     void             无返回值
// 使用示例     stmt.bind_string(1, "小明");
// 备注信息     值拷贝进对象内部 vector 覆盖 execute 全生命周期 超过 16 个参数扩容会让先前绑定的指针失效
//-------------------------------------------------------------------------------------------------------------------
  void bind_string(int index, const std::string& value);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把参数绑定为 SQL NULL
// 参数说明     index            从 0 开始的占位符序号
// 返回参数     void             无返回值
// 使用示例     stmt.bind_null(2);
// 备注信息     只置 is_null 标记 覆盖此前对该位置的 bind
//-------------------------------------------------------------------------------------------------------------------
  void bind_null(int index);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     绑定全部参数并执行语句
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     stmt.execute();
// 备注信息     先 mysql_stmt_free_result 清上次结果 绑定或执行失败抛 MysqlError 参数个数须与占位符一致
//-------------------------------------------------------------------------------------------------------------------
  void execute();
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取自增主键回填值
// 参数说明     无
// 返回参数     uint64_t         最后插入行的 AUTO_INCREMENT
// 使用示例     uint64_t id = stmt.insert_id();
// 备注信息     仅 INSERT 有意义 非自增表返回 0
//-------------------------------------------------------------------------------------------------------------------
  uint64_t insert_id() const;
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取上次执行影响的行数
// 参数说明     无
// 返回参数     uint64_t         受影响行数
// 使用示例     uint64_t n = stmt.affected_rows();
// 备注信息     UPDATE 未改变值时默认返回 0 行
//-------------------------------------------------------------------------------------------------------------------
  uint64_t affected_rows() const;

 private:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     扩容参数缓冲并重置指定位置
// 参数说明     index            从 0 开始的占位符序号
// 返回参数     void             无返回值
// 使用示例     ensure(0);  // 仅在类内部调用
// 备注信息     各 vector 同步扩到 index+1 并把该位置的 MYSQL_BIND 与 null 标记清零
//-------------------------------------------------------------------------------------------------------------------
  void ensure(int index);

  MYSQL_STMT* stmt_ = nullptr;
  std::vector<MYSQL_BIND> binds_;
  std::vector<uint64_t> u64_;
  std::vector<int> i32_;
  std::vector<std::string> strings_;
  std::vector<unsigned long> lengths_;
  std::vector<char> nulls_;
};
