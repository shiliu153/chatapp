#pragma once
#include <cstdint>
#include <mutex>
#include <optional>
#include <string>
#include <string_view>
#include <unordered_map>
#include <unordered_set>

#include "store/models.h"
#include "store/mysql_pool.h"

class UserRepo {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造仓储 绑定连接池与两个缓存上限
// 参数说明     pool             连接池引用 生命周期必须长于本对象
//              max_known        已知账号集合上限 默认 100000
//              max_profiles     画像缓存上限 默认 100000
// 返回参数     void             无返回值
// 使用示例     UserRepo repo(pool, 100000, 100000);
// 备注信息     两个上限都是硬上限 达到即整体清空 不淘汰单条
//-------------------------------------------------------------------------------------------------------------------
  explicit UserRepo(MysqlPool& pool, std::size_t max_known = 100000,
                    std::size_t max_profiles = 100000);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     确保账号行存在 不存在则插入
// 参数说明     lease            已借出的连接
//              uid              账号 id
//              nickname         昵称 仅新建时写入
// 返回参数     void             无返回值
// 使用示例     repo.ensure(lease, 42, "小明");
// 备注信息     known_ 命中直接返回 未命中先做主键读避开间隙锁 已存在只记入集合不写库
//-------------------------------------------------------------------------------------------------------------------
  void ensure(MysqlPool::Lease& lease, uint64_t uid, const std::string& nickname);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     确保账号行存在 自行借连接
// 参数说明     uid              账号 id
//              nickname         昵称 仅新建时写入
// 返回参数     void             无返回值
// 使用示例     repo.ensure(42, "小明");
// 备注信息     内部 acquire 一条连接后转调租约版本
//-------------------------------------------------------------------------------------------------------------------
  void ensure(uint64_t uid, const std::string& nickname);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按账号 id 取画像
// 参数说明     lease            已借出的连接
//              uid              账号 id
// 返回参数     std::optional<UserRow>     查不到为空
// 使用示例     auto row = repo.get(lease, 42);
// 备注信息     先查进程内 profiles_ 缓存 未命中查库并回填 昵称与头像为 NULL 时给空串
//-------------------------------------------------------------------------------------------------------------------
  std::optional<UserRow> get(MysqlPool::Lease& lease, uint64_t uid);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按账号 id 取画像 自行借连接
// 参数说明     uid              账号 id
// 返回参数     std::optional<UserRow>     查不到为空
// 使用示例     auto row = repo.get(42);
// 备注信息     先查缓存 未命中才 acquire 连接
//-------------------------------------------------------------------------------------------------------------------
  std::optional<UserRow> get(uint64_t uid);
  /// 取某账号**某一端**的会话版本(多端在线 K-2,数据源 `im_device_session`)。
  ///
  /// Args:
  ///   lease: 已借出的数据库连接。
  ///   uid: 账号 id。
  ///   ct: 端类型 `app` / `web`(来自 token 的 `ct` claim,已归一化)。
  ///
  /// Returns:
  ///   该端的会话版本;该端没有会话行(从未登录过该端)时为空。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取某账号某端的会话版本
// 参数说明     lease            已借出的数据库连接
//              uid              账号 id
//              ct               端类型 app 或 web 来自 token 的 ct claim
// 返回参数     std::optional<int64_t>     该端没有会话行时为空
// 使用示例     auto sv = repo.session_version(lease, 42, "web");
// 备注信息     数据源是 im_device_session 的 (user_id, client_type) 多端在线后版本按端存放
//-------------------------------------------------------------------------------------------------------------------
  std::optional<int64_t> session_version(MysqlPool::Lease& lease, uint64_t uid,
                                        std::string_view ct);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取某账号某端的会话版本 自行借连接
// 参数说明     uid              账号 id
//              ct               端类型 app 或 web
// 返回参数     std::optional<int64_t>     该端没有会话行时为空
// 使用示例     auto sv = repo.session_version(42, "app");
// 备注信息     内部 acquire 后转调租约版本
//-------------------------------------------------------------------------------------------------------------------
  std::optional<int64_t> session_version(uint64_t uid, std::string_view ct);
  /// 写某账号**某一端**的会话版本(upsert,同步任务可能早于端会话行存在)。
  ///
  /// Args:
  ///   lease: 已借出的数据库连接。
  ///   uid: 账号 id。
  ///   ct: 端类型 `app` / `web`。
  ///   version: 该端的新会话版本。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     写某账号某端的会话版本
// 参数说明     lease            已借出的数据库连接
//              uid              账号 id
//              ct               端类型 app 或 web
//              version          该端的新会话版本
// 返回参数     void             无返回值
// 使用示例     repo.set_session_version(lease, 42, "app", 7);
// 备注信息     upsert 端会话行不存在时补一行 供 Django 同步任务调用 失败抛 MysqlError
//-------------------------------------------------------------------------------------------------------------------
  void set_session_version(MysqlPool::Lease& lease, uint64_t uid, std::string_view ct,
                           int64_t version);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     写某账号某端的会话版本 自行借连接
// 参数说明     uid              账号 id
//              ct               端类型 app 或 web
//              version          该端的新会话版本
// 返回参数     void             无返回值
// 使用示例     repo.set_session_version(42, "web", 3);
// 备注信息     内部 acquire 后转调租约版本
//-------------------------------------------------------------------------------------------------------------------
  void set_session_version(uint64_t uid, std::string_view ct, int64_t version);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     更新昵称与头像
// 参数说明     lease            已借出的连接
//              uid              账号 id
//              nickname         有值才更新昵称
//              avatar           有值才更新头像
//              now_ms           写入 updated_at 的毫秒时间戳
// 返回参数     void             无返回值
// 使用示例     repo.update_profile(lease, 42, std::string("小明"), std::nullopt, now_ms);
// 备注信息     两个字段各发一条 UPDATE 不在同一事务 末尾清掉该账号的画像缓存
//-------------------------------------------------------------------------------------------------------------------
  void update_profile(MysqlPool::Lease& lease, uint64_t uid,
                      const std::optional<std::string>& nickname,
                      const std::optional<std::string>& avatar, int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     删除账号行与端会话行
// 参数说明     lease            已借出的连接
//              uid              账号 id
// 返回参数     void             无返回值
// 使用示例     repo.remove(lease, 42);
// 备注信息     两条 DELETE 都走预编译 调用方需在同一事务里 同时清 known_ 与 profiles_ 缓存
//-------------------------------------------------------------------------------------------------------------------
  void remove(MysqlPool::Lease& lease, uint64_t uid);
  /// 清空进程内缓存(测试清库后必须调用,否则 ensure 会误以为用户仍存在)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清空进程内缓存
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     repo.clear_cache();
// 备注信息     测试清库后必须调用 否则 ensure 会误判账号仍存在
//-------------------------------------------------------------------------------------------------------------------
  void clear_cache();

 private:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断账号是否在已知集合
// 参数说明     uid              账号 id
// 返回参数     bool             在集合内返回 true
// 使用示例     is_known(42);  // 仅在类内部调用
// 备注信息     持 known_mu_ 读 与 remember forget 互斥
//-------------------------------------------------------------------------------------------------------------------
  bool is_known(uint64_t uid);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把账号记入已知集合
// 参数说明     uid              账号 id
// 返回参数     void             无返回值
// 使用示例     remember(42);  // 仅在类内部调用
// 备注信息     达到 max_known_ 先整体清空再插入 防止随任意 uid 无限增长
//-------------------------------------------------------------------------------------------------------------------
  void remember(uint64_t uid);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     从已知集合移除账号
// 参数说明     uid              账号 id
// 返回参数     void             无返回值
// 使用示例     forget(42);  // 仅在类内部调用
// 备注信息     删除账号后调用 与 is_known 共用 known_mu_
//-------------------------------------------------------------------------------------------------------------------
  void forget(uint64_t uid);

  MysqlPool& pool_;
  std::size_t max_known_;
  /// 画像缓存的硬上限:只缓存真实用户,但同样不能无限涨(L9)。
  std::size_t max_profiles_;
  std::mutex known_mu_;
  std::unordered_set<uint64_t> known_;
  std::mutex profile_mu_;
  std::unordered_map<uint64_t, UserRow> profiles_;
};
