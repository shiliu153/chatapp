#pragma once
#include <cstdint>
#include <optional>
#include <string>
#include <vector>

#include "store/models.h"
#include "store/mysql_pool.h"

// 简介 im_message 与 im_message_hidden 两张表的访问层
// 简介 隐藏关系按 (user_id, msg_id) 存，读路径统一用 LEFT JOIN 反连接排除「我隐藏的」消息
// 简介 类内只保存连接池引用，带 lease 的重载由调用方给连接，无 lease 的重载自行 acquire 用后归还
class MessageRepo {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造消息仓库 绑定连接池
// 参数说明     pool             MySQL 连接池 只保存引用 生命周期须长于本对象
// 返回参数     void             无返回值
// 使用示例     MessageRepo repo(pool);
// 备注信息     构造函数不借连接也不访问数据库
//-------------------------------------------------------------------------------------------------------------------
  explicit MessageRepo(MysqlPool& pool);

  /// 落一条消息,返回新行的 msg_id。
  ///
  /// Args:
  ///   lease: 借出的数据库连接(调用方已开事务)。
  ///   conv_id: 会话 id。
  ///   seq: 会话内序号(调用方已加锁分配)。
  ///   from_id: 发送者;0 是系统通知。
  ///   to_id: 接收者。
  ///   kind: 1=text 2=custom 3=image 4=voice。
  ///   body: 已校验并序列化的载荷 JSON 文本。
  ///   client_msg_id: 客户端幂等 id。
  ///   now_ms: 服务端时间(毫秒)。
  ///   ref_msg_id: 引用的原消息 id(批次 L-2);无引用时为空。
  ///   ref_snapshot: **服务端生成的**引用快照 JSON 文本;无引用时为空。
  ///
  /// Returns:
  ///   新插入行的自增 id。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     落一条消息 返回新行的 msg_id
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              conv_id          会话 id
//              seq              会话内序号 调用方已加锁分配
//              from_id          发送者 user_id 0 是系统通知
//              to_id            接收者 user_id
//              kind             消息类型 1=text 2=custom 3=image 4=voice
//              body             已校验并序列化的载荷 JSON 文本
//              client_msg_id    客户端幂等 id
//              now_ms           服务端时间 毫秒
//              ref_msg_id       引用的原消息 id 无引用时 nullopt
//              ref_snapshot     服务端生成的引用快照 JSON 无引用时 nullopt
// 返回参数     uint64_t         新插入行的自增 id
// 使用示例     repo.insert(lease, conv_id, seq, from, to, 1, body, client_msg_id, now);
// 备注信息     无引用时两列写 NULL 而不是 0 或空串 读侧据此决定 ref 键是否出现 唯一键冲突抛 MysqlError(1062)
//-------------------------------------------------------------------------------------------------------------------
  uint64_t insert(MysqlPool::Lease& lease, uint64_t conv_id, uint64_t seq, uint64_t from_id,
                  uint64_t to_id, int kind, const std::string& body,
                  const std::string& client_msg_id, int64_t now_ms,
                  const std::optional<uint64_t>& ref_msg_id = std::nullopt,
                  const std::optional<std::string>& ref_snapshot = std::nullopt);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按发送者与客户端幂等 id 查已落库的消息
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              from_id          发送者 user_id
//              client_msg_id    客户端幂等 id
// 返回参数     std::optional<MessageRow>  命中时返回消息行 否则 nullopt
// 使用示例     repo.find_by_client(lease, from, client_msg_id);
// 备注信息     client_msg_id 先经 lease.escape 转义再拼进 SQL 用于 1062 冲突后的幂等重放
//-------------------------------------------------------------------------------------------------------------------
  std::optional<MessageRow> find_by_client(MysqlPool::Lease& lease, uint64_t from_id,
                                           const std::string& client_msg_id);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按发送者与客户端幂等 id 查已落库的消息 自行借连接
// 参数说明     from_id          发送者 user_id
//              client_msg_id    客户端幂等 id
// 返回参数     std::optional<MessageRow>  命中时返回消息行 否则 nullopt
// 使用示例     repo.find_by_client(from, client_msg_id);
// 备注信息     自动 acquire 一条连接 用后归还
//-------------------------------------------------------------------------------------------------------------------
  std::optional<MessageRow> find_by_client(uint64_t from_id, const std::string& client_msg_id);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按 msg_id 取一条消息
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              msg_id           消息 id
// 返回参数     std::optional<MessageRow>  命中时返回消息行 否则 nullopt
// 使用示例     repo.get(lease, msg_id);
// 备注信息     按主键等值查 撤回后 revoked_at 有值但行仍在
//-------------------------------------------------------------------------------------------------------------------
  std::optional<MessageRow> get(MysqlPool::Lease& lease, uint64_t msg_id);
  /// 历史分页:**排除「我隐藏的」**(批次 T 的多选删除)。
  ///
  /// 隐藏关系在 `im_message_hidden`,用 `LEFT JOIN + h.msg_id IS NULL` 排除。这个写法
  /// 必须仍走 `uk_conv_seq(conv_id,seq)`:隐藏行很少,`LEFT JOIN` 是主键点查,不会退化成
  /// 全表扫(EXPLAIN 断言见 `docs/ops/imserver.md` §21)。
  ///
  /// Args:
  ///   lease: 借出的数据库连接。
  ///   owner: 请求者账号(决定排除哪一份隐藏关系)。
  ///   conv_id: 会话 id。
  ///   before_seq: 游标,只取 seq 小于它的消息;0 表示最新一页。
  ///   limit: 最多返回条数(1–100)。
  ///
  /// Returns:
  ///   旧 → 新排列的消息行。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     分页取会话历史 排除我隐藏的消息
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            请求者 user_id 决定排除哪一份隐藏关系
//              conv_id          会话 id
//              before_seq       游标 只取 seq 小于它的消息 0 表示最新一页
//              limit            最多返回条数 内部夹在 1..100
// 返回参数     std::vector<MessageRow>  旧到新排列的消息行
// 使用示例     repo.list(lease, uid, conv_id, 0, 30);
// 备注信息     SQL 按 seq 倒序取再在内存里反转 LEFT JOIN im_message_hidden 反连接 仍走 uk_conv_seq
//-------------------------------------------------------------------------------------------------------------------
  std::vector<MessageRow> list(MysqlPool::Lease& lease, uint64_t owner, uint64_t conv_id,
                               uint64_t before_seq, int limit);
  /// 从一批 msg_id 里挑出「真实存在且我参与」的消息行(多选删除的前置查询)。
  ///
  /// 不属于我的 id **不报错也不返回** —— 报错会变成「探测别人消息是否存在」的信道。
  ///
  /// Args:
  ///   lease: 借出的数据库连接。
  ///   owner: 请求者账号。
  ///   ids: 候选 msg_id(调用方已去重、已限量 ≤ 50)。
  ///
  /// Returns:
  ///   命中的消息行(顺序不保证)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     从一批 msg_id 里挑出我参与且真实存在的消息
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            请求者 user_id
//              ids              候选 msg_id 调用方已去重且不超过 50 个
// 返回参数     std::vector<MessageRow>  命中的消息行 顺序不保证
// 使用示例     repo.find_mine(lease, uid, ids);
// 备注信息     不属于我的 id 既不报错也不返回 避免变成探测他人消息是否存在的信道
//-------------------------------------------------------------------------------------------------------------------
  std::vector<MessageRow> find_mine(MysqlPool::Lease& lease, uint64_t owner,
                                    const std::vector<uint64_t>& ids);
  /// 落一条「我不再看到这条消息」的隐藏关系。
  ///
  /// 用 `INSERT IGNORE` + `affected_rows` 区分「本次新隐藏」与「早就删过」,接口的
  /// 幂等语义(`{"deleted": n}` 第二次必须是 0)就建立在这个返回值上。
  ///
  /// Args:
  ///   lease: 借出的数据库连接(调用方已开事务)。
  ///   owner: 隐藏这条消息的人。
  ///   msg_id: 消息 id。
  ///   now_ms: 当前毫秒时间戳。
  ///
  /// Returns:
  ///   true = 本次新隐藏;false = 这一行本来就存在(幂等重放)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     记录我不再看到某条消息 返回本次是否新隐藏
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            执行隐藏的 user_id
//              msg_id           消息 id
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     bool             true 表示本次新隐藏 false 表示这一行本来就存在
// 使用示例     repo.hide(lease, uid, msg_id, now);
// 备注信息     INSERT IGNORE 靠主键 (user_id,msg_id) 幂等 用 affected_rows 是否为 1 区分 调用方按返回值累加未读减量
//-------------------------------------------------------------------------------------------------------------------
  bool hide(MysqlPool::Lease& lease, uint64_t owner, uint64_t msg_id, int64_t now_ms);
  /// 我在这个会话里**最后一条可见消息**;一条都没有(或全被我隐藏)时 `nullopt`。
  ///
  /// 走 `uk_conv_seq(conv_id,seq)` **反向扫 + LIMIT 1**:隐藏行 ≤ 几条,所以实际只读
  /// 「被隐藏的条数 + 1」行,不会扫整段历史(EXPLAIN 见 `docs/ops/imserver.md` §21)。
  ///
  /// Args:
  ///   lease: 借出的数据库连接。
  ///   owner: 请求者账号(决定排除哪一份隐藏关系)。
  ///   conv_id: 会话 id。
  ///
  /// Returns:
  ///   最后一条可见消息行;没有时 `nullopt`。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     取我在某个会话里的最后一条可见消息
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            请求者 user_id 决定排除哪一份隐藏关系
//              conv_id          会话 id
// 返回参数     std::optional<MessageRow>  最后一条可见消息 没有可见消息时 nullopt
// 使用示例     repo.last_visible(lease, uid, conv_id);
// 备注信息     按 seq 倒序加 LIMIT 1 只读被隐藏条数加一行 不扫整段历史
//-------------------------------------------------------------------------------------------------------------------
  std::optional<MessageRow> last_visible(MysqlPool::Lease& lease, uint64_t owner,
                                         uint64_t conv_id);
  /// 把会话列表的 `last_message` 修成「**我的**最后一条可见消息」(批次 T)。
  ///
  /// 为什么不在列表 SQL 里直接写相关子查询:`c.last_msg_id` 被我隐藏时才会用到回退,
  /// 而相关子查询的形式在 MySQL 8 上会**把整段会话历史读出来再排序**(实测 2000 条的
  /// 会话每条列表项 0.4ms 全量扫,50 个会话 × 2000 条 ≈ 60ms)。这里改成:
  /// 先照旧 join `c.last_msg_id`,只有「这条摘要确实被我隐藏了」的会话才回查一次
  /// —— 绝大多数会话一条额外查询都不用。
  ///
  /// 语义:`last_seq` / `has_last` / `updated_at` 都不动(仍是会话全局);只换摘要。
  ///
  /// Args:
  ///   lease: 借出的数据库连接。
  ///   owner: 列表的主人。
  ///   views: 已按服务端顺序排好的会话列表(原地修补)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把会话列表的摘要修成我的最后一条可见消息
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            列表主人 user_id
//              views            待原地修补的会话列表
// 返回参数     void             无返回值
// 使用示例     repo.apply_visible_last(lease, uid, views);
// 备注信息     先一次 IN 查询问清哪些摘要被我隐藏 没有命中就整体返回 只对被隐藏的那几项回查 last_visible
//-------------------------------------------------------------------------------------------------------------------
  void apply_visible_last(MysqlPool::Lease& lease, uint64_t owner,
                          std::vector<ConversationView>& views);
  /// 注销清理第一步:删掉「我隐藏过别人消息」的那些行。
  ///
  /// Args:
  ///   lease: 借出的数据库连接。
  ///   uid: 要注销的账号。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     注销清理 删掉我隐藏别人消息的那些行
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              uid              要注销的账号 user_id
// 返回参数     void             无返回值
// 使用示例     repo.delete_hidden_by_user(lease, uid);
// 备注信息     按 user_id 一次删除 必须与 delete_hidden_by_messages 一起在删 im_message 之前跑
//-------------------------------------------------------------------------------------------------------------------
  void delete_hidden_by_user(MysqlPool::Lease& lease, uint64_t uid);
  /// 注销清理第二步:删掉「别人隐藏了我的消息」的那些行。
  ///
  /// **必须在 `delete_for_user`(删 `im_message`)之前跑**:它靠 `im_message` 里
  /// `from_id/to_id = uid` 的行反查 msg_id,消息删掉之后就再也查不到了。
  ///
  /// Args:
  ///   lease: 借出的数据库连接。
  ///   uid: 要注销的账号。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     注销清理 删掉别人隐藏了我消息的那些行
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              uid              要注销的账号 user_id
// 返回参数     void             无返回值
// 使用示例     repo.delete_hidden_by_messages(lease, uid);
// 备注信息     用 im_message 里 from_id 或 to_id 为 uid 的行反查 msg_id 所以必须在删消息之前执行
//-------------------------------------------------------------------------------------------------------------------
  void delete_hidden_by_messages(MysqlPool::Lease& lease, uint64_t uid);
  /// 关键词搜索:只搜我参与的、未删除会话里的未撤回文本消息,按 msg_id 倒序。
  ///
  /// Args:
  ///   lease: 借出的数据库连接。
  ///   uid: 请求者账号(只能搜到自己参与的会话)。
  ///   keyword: 用户关键词(内部按 LIKE 转义,大小写不敏感)。
  ///   before_id: 游标,只取 msg_id 小于它的消息;0 表示第一页。
  ///   limit: 最多返回条数(1–100)。
  ///
  /// Returns:
  ///   命中的消息行,新 → 旧。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     关键词搜索我参与的未撤回文本消息
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              uid              请求者 user_id 只能搜到自己参与的会话
//              keyword          用户关键词 内部按 LIKE 转义 大小写不敏感
//              before_id        游标 只取 msg_id 小于它的消息 0 表示第一页
//              limit            最多返回条数 内部夹在 1..100
// 返回参数     std::vector<MessageRow>  命中的消息行 新到旧
// 使用示例     repo.search(lease, uid, keyword, 0, 20);
// 备注信息     只搜 kind=1 且未撤回 排除已删除会话与我隐藏的消息 也排除我拉黑的对端
//-------------------------------------------------------------------------------------------------------------------
  std::vector<MessageRow> search(MysqlPool::Lease& lease, uint64_t uid,
                                 const std::string& keyword, uint64_t before_id, int limit);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     关键词搜索我参与的未撤回文本消息 自行借连接
// 参数说明     uid              请求者 user_id
//              keyword          用户关键词 内部按 LIKE 转义
//              before_id        游标 只取 msg_id 小于它的消息 0 表示第一页
//              limit            最多返回条数 内部夹在 1..100
// 返回参数     std::vector<MessageRow>  命中的消息行 新到旧
// 使用示例     repo.search(uid, keyword, 0, 20);
// 备注信息     自动 acquire 一条连接 用后归还
//-------------------------------------------------------------------------------------------------------------------
  std::vector<MessageRow> search(uint64_t uid, const std::string& keyword, uint64_t before_id,
                                 int limit);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把一条消息标记为已撤回
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              msg_id           要撤回的消息 id
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     void             无返回值
// 使用示例     repo.revoke(lease, msg_id, now);
// 备注信息     只写 revoked_at 不删行 发送者与 120 秒窗口由 MessageService::revoke 先校验
//-------------------------------------------------------------------------------------------------------------------
  void revoke(MysqlPool::Lease& lease, uint64_t msg_id, int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     统计两个人在同一会话里的消息总数
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              a                会话一方 user_id
//              b                会话另一方 user_id
// 返回参数     uint64_t         该会话的消息条数 没有会话时 0
// 使用示例     repo.count_pair(lease, 1, 2);
// 备注信息     先规范化成升序对再经 uk_pair 关联 im_conversation 计数 包含已撤回与我隐藏的消息
//-------------------------------------------------------------------------------------------------------------------
  uint64_t count_pair(MysqlPool::Lease& lease, uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     统计两个人在同一会话里的消息总数 自行借连接
// 参数说明     a                会话一方 user_id
//              b                会话另一方 user_id
// 返回参数     uint64_t         该会话的消息条数 没有会话时 0
// 使用示例     repo.count_pair(1, 2);
// 备注信息     自动 acquire 一条连接 用后归还
//-------------------------------------------------------------------------------------------------------------------
  uint64_t count_pair(uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     注销时删掉该账号收发过的全部消息
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              uid              要注销的账号 user_id
// 返回参数     void             无返回值
// 使用示例     repo.delete_for_user(lease, uid);
// 备注信息     按 from_id 或 to_id 删 必须在两个 delete_hidden_* 之后执行 由 MessageService::delete_account 在同一事务内调用
//-------------------------------------------------------------------------------------------------------------------
  void delete_for_user(MysqlPool::Lease& lease, uint64_t uid);

 private:
  MysqlPool& pool_;
};
