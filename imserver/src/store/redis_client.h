#pragma once
#include <hiredis/hiredis.h>

#include <mutex>
#include <optional>
#include <string>

/// Redis 连接参数,由 `redis://[user][:password]@host:port/db` 解析而来。
///
/// E-6②:此前不支持口令,生产只能让 Redis 裸奔(任何能连到 6379 的进程都能改数据)。
/// 现在支持两种写法:
///   - `redis://:pass@host:6379/2`      —— 默认用户 + 口令(最常见)
///   - `redis://user:pass@host:6379/2`  —— Redis 6 ACL 用户名 + 口令
/// 口令里的特殊字符用百分号编码(如 `@` 写成 `%40`),解析时会解码。
struct RedisUrlParts {
  std::string host;
  int port = 6379;
  int db = 0;
  std::string user;
  std::string password;
};

/// 解析 Redis URL。非法格式抛 ``std::invalid_argument``。
///
/// Args:
///   url: 形如 ``redis://host:6379/0`` 的地址。
///
/// Returns:
///   解析结果(未给口令时 ``password`` 为空,构造函数不会发 ``AUTH``)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     解析 Redis URL 成连接参数
// 参数说明     url              形如 redis://[user:pass@]host:port/db
// 返回参数     RedisUrlParts     主机 端口 库号 账号 口令
// 使用示例     RedisUrlParts parts = parse_redis_url("redis://:pass@127.0.0.1:6379/2");
// 备注信息     非法格式抛 std::invalid_argument 口令支持 %XX 百分号编码
//-------------------------------------------------------------------------------------------------------------------
RedisUrlParts parse_redis_url(const std::string& url);

class RedisClient {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造客户端 连接并按需鉴权选库
// 参数说明     url              Redis URL 口令可选 库号非 0 时执行 SELECT
// 返回参数     void             无返回值
// 使用示例     RedisClient client("redis://127.0.0.1:6379/2");
// 备注信息     连接 AUTH SELECT 任一步失败都先 redisFree 再抛 std::runtime_error 超时 2 秒
//-------------------------------------------------------------------------------------------------------------------
  explicit RedisClient(const std::string& url);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     析构客户端 释放连接上下文
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     { RedisClient client(url); }
// 备注信息     只 redisFree 不发送 QUIT 析构不抛异常
//-------------------------------------------------------------------------------------------------------------------
  ~RedisClient();
  RedisClient(const RedisClient&) = delete;
  RedisClient& operator=(const RedisClient&) = delete;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     写入带过期时间的字符串
// 参数说明     key              键名
//              ttl_seconds      过期秒数
//              value            字符串值
// 返回参数     bool             命令执行成功返回 true
// 使用示例     client.setex("im:token:42", 3600, "1");
// 备注信息     持锁串行执行 命令失败只返回 false 不抛异常
//-------------------------------------------------------------------------------------------------------------------
  bool setex(const std::string& key, int ttl_seconds, const std::string& value);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取字符串值
// 参数说明     key              键名
// 返回参数     std::optional<std::string>     键不存在或命令出错时为空
// 使用示例     auto value = client.get("im:token:42");
// 备注信息     按回复长度取串 二进制安全 空字符串返回有值但长度为 0 的串
//-------------------------------------------------------------------------------------------------------------------
  std::optional<std::string> get(const std::string& key);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     删除键
// 参数说明     key              键名
// 返回参数     bool             命令执行成功返回 true 键不存在也为 true
// 使用示例     client.del("im:token:42");
// 备注信息     只判断回复类型为整数 不解析实际删除个数
//-------------------------------------------------------------------------------------------------------------------
  bool del(const std::string& key);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     自增计数
// 参数说明     key              键名
// 返回参数     long long        自增后的值 出错返回 0
// 使用示例     long long n = client.incr("im:rate:42");
// 备注信息     键不存在按 0 起算 出错与真实值 0 无法区分
//-------------------------------------------------------------------------------------------------------------------
  long long incr(const std::string& key);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     探测连接可用性
// 参数说明     无
// 返回参数     bool             收到 PONG 状态回复返回 true
// 使用示例     client.ping();
// 备注信息     只判断回复类型为状态 失败不重连
//-------------------------------------------------------------------------------------------------------------------
  bool ping();

 private:
  redisContext* ctx_ = nullptr;
  std::mutex mutex_;
};
