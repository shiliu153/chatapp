#pragma once
#include <cstdint>
#include <map>
#include <optional>
#include <vector>

#include "store/models.h"
#include "store/mysql_pool.h"

// 简介 im_conversation 与 im_conversation_state 两张表的访问层
// 简介 会话行按 (user_a < user_b) 规范化存一份，状态行按 (owner_id, conv_id) 存每个人的未读与已读位置
// 简介 发送热路径靠 lock_pair 分配 seq，其余写方法都要求调用方已开事务
class ConversationRepo {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造会话仓库 绑定连接池
// 参数说明     pool             MySQL 连接池 只保存引用 生命周期须长于本对象
// 返回参数     void             无返回值
// 使用示例     ConversationRepo repo(pool);
// 备注信息     构造函数不借连接也不访问数据库
//-------------------------------------------------------------------------------------------------------------------
  explicit ConversationRepo(MysqlPool& pool);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按两人查会话行 不存在时返回空
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              a                会话一方 user_id
//              b                会话另一方 user_id
// 返回参数     std::optional<ConversationRow>  命中时返回会话行 未配对时 nullopt
// 使用示例     repo.find_pair(lease, uid, peer);
// 备注信息     先把两人规范化成 (小,大) 再按 uk_pair 等值查 不加锁 不建行
//-------------------------------------------------------------------------------------------------------------------
  std::optional<ConversationRow> find_pair(MysqlPool::Lease& lease, uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     建或取会话 id 并对会话行加写锁
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              a                会话一方 user_id
//              b                会话另一方 user_id
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     ConversationRow  加锁后读到的会话行 last_seq 可直接用于分配新序号
// 使用示例     repo.lock_pair(lease, from, to, now_ms());
// 备注信息     必须在事务内调用 会话不存在时顺带建行 取行失败抛 std::runtime_error
//-------------------------------------------------------------------------------------------------------------------
  ConversationRow lock_pair(MysqlPool::Lease& lease, uint64_t a, uint64_t b, int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     更新会话的最后一条消息与已分配序号
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              conv_id          会话 id
//              seq              刚分配的会话内序号
//              msg_id           刚落库的消息 id
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     void             无返回值
// 使用示例     repo.touch(lease, conv.id, seq, msg_id, now);
// 备注信息     写 last_seq / last_msg_id / last_msg_at 三列 须与消息插入同事务
//-------------------------------------------------------------------------------------------------------------------
  void touch(MysqlPool::Lease& lease, uint64_t conv_id, uint64_t seq, uint64_t msg_id,
             int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     累加某个人的会话状态 没有状态行时先插入
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            状态所属 user_id
//              conv_id          会话 id
//              unread_delta     未读数增量 正数累加
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     void             无返回值
// 使用示例     repo.upsert_state(lease, owner, conv_id, 1, now);
// 备注信息     新行的 read_seq 从 0 开始 冲突分支做 unread 加法并把 deleted 复位成 0
//-------------------------------------------------------------------------------------------------------------------
  void upsert_state(MysqlPool::Lease& lease, uint64_t owner, uint64_t conv_id,
                    int unread_delta, int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     一条多行 INSERT 同时累加收发双方的状态
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner_a          第一个状态所属 user_id
//              delta_a          第一个人的未读增量
//              owner_b          第二个状态所属 user_id
//              delta_b          第二个人的未读增量
//              conv_id          会话 id
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     void             无返回值
// 使用示例     repo.upsert_states(lease, to, 1, from, 0, conv.id, now);
// 备注信息     owner_b 为 0 时退化成只写 owner_a 一条 发送热路径用它省一次往返 语义同 upsert_state
//-------------------------------------------------------------------------------------------------------------------
  void upsert_states(MysqlPool::Lease& lease, uint64_t owner_a, int delta_a, uint64_t owner_b,
                     int delta_b, uint64_t conv_id, int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查某人在某个会话里的未读条数
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            状态所属 user_id
//              peer             会话对端 user_id
// 返回参数     uint32_t         未读条数 没有状态行时返回 0
// 使用示例     repo.unread_for_peer(lease, 2, 1);
// 备注信息     先经 uk_pair 定位会话 再按 (owner_id,conv_id) 主键取 unread
//-------------------------------------------------------------------------------------------------------------------
  uint32_t unread_for_peer(MysqlPool::Lease& lease, uint64_t owner, uint64_t peer);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查某人在某个会话里的未读条数 自行借连接
// 参数说明     owner            状态所属 user_id
//              peer             会话对端 user_id
// 返回参数     uint32_t         未读条数 没有状态行时返回 0
// 使用示例     repo.unread_for_peer(2, 1);
// 备注信息     自动 acquire 一条连接 用后归还
//-------------------------------------------------------------------------------------------------------------------
  uint32_t unread_for_peer(uint64_t owner, uint64_t peer);
  /// 读「owner 自己那一行」的 read_seq(即 owner 读到哪);没有行时返回 0。
  ///
  /// 已读回执广播要的是**写完之后**的准确值(`mark_read` 里是 `GREATEST`,乱序到达的
  /// 旧 `read` 帧不会让值回退),所以必须回读,而不是拿请求里带的 seq 直接广播出去。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     回读某人在某个会话里已读到的序号
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            状态所属 user_id
//              peer             会话对端 user_id
// 返回参数     uint64_t         已读位置 read_seq 没有状态行时返回 0 表示从没读过
// 使用示例     repo.read_seq_for(lease, uid, peer);
// 备注信息     mark_read 落库用 GREATEST 广播必须带这条回读的真实值 不能拿请求里的 seq 直接推
//-------------------------------------------------------------------------------------------------------------------
  uint64_t read_seq_for(MysqlPool::Lease& lease, uint64_t owner, uint64_t peer);
  /// 批量读「我在这些会话里的 read_seq」(多选删除时判断哪些条还没读)。
  ///
  /// Args:
  ///   lease: 借出的数据库连接。
  ///   owner: 会话主人。
  ///   conv_ids: 会话 id 列表(调用方已去重)。
  ///
  /// Returns:
  ///   `conv_id → read_seq`;没有状态行的会话不出现在结果里(等价于「从没读过」)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     批量查某人在多个会话里的已读位置
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            状态所属 user_id
//              conv_ids         会话 id 列表 调用方已去重且非空
// 返回参数     std::map<uint64_t, uint64_t>  conv_id 到 read_seq 的映射 没有状态行的会话不出现在结果里
// 使用示例     repo.read_seqs(lease, uid, conv_ids);
// 备注信息     conv_ids 为空直接返回空表 id 由 uint64 拼成 IN 列表 调用方负责限量
//-------------------------------------------------------------------------------------------------------------------
  std::map<uint64_t, uint64_t> read_seqs(MysqlPool::Lease& lease, uint64_t owner,
                                         const std::vector<uint64_t>& conv_ids);
  /// 删除未读消息后**按条数减**未读(批次 T 的多选删除)。
  ///
  /// 为什么必须显式减:`im_conversation_state.unread` 是**计数器**(`upsert_state` 累加、
  /// `mark_read` 清零),不是每次现算的聚合,所以「排除隐藏行」在这条链路上加个
  /// `NOT EXISTS` 不会让数字变小,只会让数字永远对不上。
  ///
  /// `CAST(unread AS SIGNED)` 不能省:`unread` 是 `INT UNSIGNED`,无符号相减一旦越过 0
  /// 就报 `BIGINT UNSIGNED value is out of range`(1690),而不是变成负数。
  ///
  /// Args:
  ///   lease: 借出的数据库连接(调用方已开事务)。
  ///   owner: 会话主人。
  ///   conv_id: 会话 id。
  ///   delta: 要减掉的未读条数(必须 > 0)。
  ///   now_ms: 当前毫秒时间戳(写 `updated_at`)。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按条数减未读 减到 0 为止
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            状态所属 user_id
//              conv_id          会话 id
//              delta            要减掉的未读条数 小于等于 0 时直接返回
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     void             无返回值
// 使用示例     repo.decrement_unread(lease, uid, conv_id, 2, now);
// 备注信息     unread 是 INT UNSIGNED 必须先 CAST 成有符号再相减 否则越过 0 报 1690 相减结果再由 GREATEST 夹到 0
//-------------------------------------------------------------------------------------------------------------------
  void decrement_unread(MysqlPool::Lease& lease, uint64_t owner, uint64_t conv_id, int delta,
                        int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把某人在某个会话的已读位置推进到 seq 并清零未读
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            状态所属 user_id
//              peer             会话对端 user_id
//              seq              本次读到的会话内序号
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     void             无返回值
// 使用示例     repo.mark_read(lease, uid, peer, target, now_ms());
// 备注信息     read_seq 取 GREATEST(read_seq,?) 乱序旧帧不会让已读位置回退 unread 一律清零
//-------------------------------------------------------------------------------------------------------------------
  void mark_read(MysqlPool::Lease& lease, uint64_t owner, uint64_t peer, uint64_t seq,
                 int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     单方隐藏整个会话 只改自己那一行
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            执行删除的 user_id
//              peer             会话对端 user_id
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     void             无返回值
// 使用示例     repo.set_deleted(lease, uid, peer, now_ms());
// 备注信息     置 deleted=1 不动 unread 与 read_seq 对端不受影响 列表查询按 deleted=0 过滤
//-------------------------------------------------------------------------------------------------------------------
  void set_deleted(MysqlPool::Lease& lease, uint64_t owner, uint64_t peer, int64_t now_ms);
  /// 改会话的置顶 / 免打扰(批次 N),返回**回读实库**后的真实值。
  ///
  /// 语义:
  ///   - `pinned` 由「假 → 真」时把 `pinned_at` 写成 `now_ms`(毫秒),取消置顶写 0;
  ///     已经置顶再置顶一次**不重写时间**(否则重复点一次就会把会话顶到置顶组最前,
  ///     不幂等);
  ///   - `muted` 直接写 0/1;
  ///   - 两个入参都可以是 `nullopt`,表示「这一项不改」。
  ///
  /// 置顶 / 免打扰是**单方**的(只写 owner 自己那一行),不通知对端,也不改 `updated_at`
  /// —— `updated_at` 是会话活动时间,标志位变化不是活动。
  ///
  /// Args:
  ///   lease: 已租用的连接。
  ///   owner: 会话主人。
  ///   peer: 会话对端。
  ///   pinned: 置顶开关;`nullopt` = 不改。
  ///   muted: 免打扰开关;`nullopt` = 不改。
  ///   now_ms: 当前毫秒时间戳(新置顶时间用它)。
  ///
  /// Returns:
  ///   写完回读到的真实标志位;会话不存在(未配对 / 从没聊过 / 没有状态行)时 `nullopt`。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     改会话的置顶与免打扰 返回回读的真实值
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            会话主人 user_id
//              peer             会话对端 user_id
//              pinned           置顶开关 nullopt 表示这一项不改
//              muted            免打扰开关 nullopt 表示这一项不改
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     std::optional<ConversationFlags>  回读到的真实标志位 会话不存在时 nullopt
// 使用示例     repo.set_flags(lease, uid, peer, true, std::nullopt, now_ms());
// 备注信息     置顶由假变真才写 pinned_at=now_ms 重复置顶不重写时间 会话不存在时不插新行 由上层回 404
//-------------------------------------------------------------------------------------------------------------------
  std::optional<ConversationFlags> set_flags(MysqlPool::Lease& lease, uint64_t owner,
                                             uint64_t peer, std::optional<bool> pinned,
                                             std::optional<bool> muted, int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按置顶与活跃时间取会话列表
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            列表主人 user_id
//              limit            最多返回条数 内部夹在 1..200
// 返回参数     std::vector<ConversationView>  会话列表项 置顶组在前
// 使用示例     repo.list(lease, uid, 50);
// 备注信息     过滤 deleted=0 置顶组内按 pinned_at 倒序 两组内都按 last_msg_at 倒序 摘要可能是已被我隐藏的那条
//-------------------------------------------------------------------------------------------------------------------
  std::vector<ConversationView> list(MysqlPool::Lease& lease, uint64_t owner, int limit);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     注销时删掉该账号的会话状态行与涉及的会话行
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              uid              要注销的账号 user_id
// 返回参数     void             无返回值
// 使用示例     repo.delete_for_user(lease, uid);
// 备注信息     先删 owner_id=uid 的状态行 再删 user_a 或 user_b 为 uid 的会话行 由 MessageService::delete_account 在同一事务内调用
//-------------------------------------------------------------------------------------------------------------------
  void delete_for_user(MysqlPool::Lease& lease, uint64_t uid);

 private:
  /// 按 `(owner, conv_id)` 读标志位;没有这一行时 `nullopt`。
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按 (owner, conv_id) 读置顶与免打扰标志位
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            会话主人 user_id
//              conv_id          会话 id
// 返回参数     std::optional<ConversationFlags>  标志位 没有这一行时 nullopt
// 使用示例     flags_of(lease, owner, conv_id);
// 备注信息     私有方法 供 set_flags 回读使用 按主键等值查
//-------------------------------------------------------------------------------------------------------------------
  std::optional<ConversationFlags> flags_of(MysqlPool::Lease& lease, uint64_t owner,
                                            uint64_t conv_id);

  MysqlPool& pool_;
};
