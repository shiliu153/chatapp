#pragma once
#include <cstdint>

#include "store/mysql_pool.h"

// 简介 im_blacklist 表的访问层，负责拉黑关系的增删与双向判定
// 简介 关系按 (owner_id, peer_id) 主键唯一存一份，同一对账号可能两个方向各有一行
// 简介 类内只保存连接池引用，带 lease 的重载由调用方给连接，无 lease 的重载自行 acquire 用后归还
class BlacklistRepo {
 public:
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     构造拉黑仓库 绑定连接池
// 参数说明     pool             MySQL 连接池 只保存引用 生命周期须长于本对象
// 返回参数     void             无返回值
// 使用示例     BlacklistRepo repo(pool);
// 备注信息     构造函数不借连接也不访问数据库
//-------------------------------------------------------------------------------------------------------------------
  explicit BlacklistRepo(MysqlPool& pool);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     写一条拉黑关系 已存在则忽略
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            拉黑发起方 user_id
//              peer             被拉黑方 user_id
//              now_ms           当前毫秒时间戳 写入时间列
// 返回参数     void             无返回值
// 使用示例     repo.add(lease, 1, 2, now_ms());
// 备注信息     INSERT IGNORE 靠主键 (owner_id,peer_id) 去重 重复拉黑是幂等的 不开事务
//-------------------------------------------------------------------------------------------------------------------
  void add(MysqlPool::Lease& lease, uint64_t owner, uint64_t peer, int64_t now_ms);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     写一条拉黑关系 自行借连接并取当前时间
// 参数说明     owner            拉黑发起方 user_id
//              peer             被拉黑方 user_id
// 返回参数     void             无返回值
// 使用示例     repo.add(1, 2);
// 备注信息     自动 acquire 一条连接 用后归还 单条 INSERT 自动提交
//-------------------------------------------------------------------------------------------------------------------
  void add(uint64_t owner, uint64_t peer);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     删除一条拉黑关系
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              owner            拉黑发起方 user_id
//              peer             被拉黑方 user_id
// 返回参数     void             无返回值
// 使用示例     repo.remove(lease, 1, 2);
// 备注信息     按主键等值 DELETE 关系不存在时影响 0 行且不报错
//-------------------------------------------------------------------------------------------------------------------
  void remove(MysqlPool::Lease& lease, uint64_t owner, uint64_t peer);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断两人之间是否存在任一方向的拉黑关系
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              a                参与判定的第一个 user_id
//              b                参与判定的第二个 user_id
// 返回参数     bool             true 表示 a 拉黑 b 或 b 拉黑 a 任一成立
// 使用示例     repo.exists_either(lease, from, to);
// 备注信息     双向 OR 等值查询 id 由 uint64 直接拼成字面量 命中即停 LIMIT 1
//-------------------------------------------------------------------------------------------------------------------
  bool exists_either(MysqlPool::Lease& lease, uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     判断两人之间是否存在任一方向的拉黑关系 自行借连接
// 参数说明     a                参与判定的第一个 user_id
//              b                参与判定的第二个 user_id
// 返回参数     bool             true 表示任一方向存在拉黑关系
// 使用示例     repo.exists_either(1, 2);
// 备注信息     自动 acquire 一条连接 用后归还
//-------------------------------------------------------------------------------------------------------------------
  bool exists_either(uint64_t a, uint64_t b);
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     注销时清掉该账号两个方向的全部拉黑关系
// 参数说明     lease            借出的数据库连接 事务边界由调用方决定
//              uid              要注销的账号 user_id
// 返回参数     void             无返回值
// 使用示例     repo.delete_for_user(lease, uid);
// 备注信息     同时删 owner_id 与 peer_id 两个方向 由 MessageService::delete_account 在同一事务内调用
//-------------------------------------------------------------------------------------------------------------------
  void delete_for_user(MysqlPool::Lease& lease, uint64_t uid);

 private:
  MysqlPool& pool_;
};
