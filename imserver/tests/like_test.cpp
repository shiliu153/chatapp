#include <gtest/gtest.h>

#include "util/like.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     用例 验证关键词被包成前后带通配符的 LIKE 模式串
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     ctest -R LikeTest.WrapsKeywordWithPercent
// 备注信息     覆盖无特殊字符时只加前后 % 中文关键词按原样保留 结果串供 prepared statement 绑定
//-------------------------------------------------------------------------------------------------------------------
TEST(LikeTest, WrapsKeywordWithPercent) {
  EXPECT_EQ(like_pattern("火锅"), "%火锅%");
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     用例 验证 LIKE 特殊字符按 ! 逐个转义
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     ctest -R LikeTest.EscapesWildcardsAndEscapeChar
// 备注信息     覆盖 % 与 _ 以及转义符 ! 本身各插一个 ! 100% 变 %100!%% a_b 变 %a!_b%
//              !! 变 %!!!!% 调用方 SQL 必须写 LIKE ? ESCAPE '!'
//-------------------------------------------------------------------------------------------------------------------
TEST(LikeTest, EscapesWildcardsAndEscapeChar) {
  EXPECT_EQ(like_pattern("100%"), "%100!%%");
  EXPECT_EQ(like_pattern("a_b"), "%a!_b%");
  EXPECT_EQ(like_pattern("!!"), "%!!!!%");
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     用例 验证不含特殊字符的关键词原样保留
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     ctest -R LikeTest.KeepsPlainTextUntouched
// 备注信息     覆盖 c++ 2.0 里的加号与空格不被转义 空串返回 %% 在 LIKE 下会匹配全部 因此调用方需自行拒绝空关键词
//-------------------------------------------------------------------------------------------------------------------
TEST(LikeTest, KeepsPlainTextUntouched) {
  EXPECT_EQ(like_pattern("c++ 2.0"), "%c++ 2.0%");
  EXPECT_EQ(like_pattern(""), "%%");
}
