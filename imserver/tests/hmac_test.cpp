#include <gtest/gtest.h>

#include "util/hmac.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     用例 验证 HMAC-SHA256 结果与标准测试向量一致
// 参数说明     无
// 返回参数     void             无返回值
// 使用示例     ctest -R HmacTest.KnownVector
// 备注信息     key 取 key data 取 RFC 里的经典英文句子 断言 64 字符小写十六进制摘要
//              服务端内部鉴权与 Django 侧同算法
//-------------------------------------------------------------------------------------------------------------------
TEST(HmacTest, KnownVector) {
  EXPECT_EQ(hmac_sha256_hex("key", "The quick brown fox jumps over the lazy dog"),
            "f7bc83f430538424b13298e6aa6fb143ef4d59a14946175997479dbc2d1a3cd8");
}
